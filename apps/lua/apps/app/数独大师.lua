-- 按可用宽度裁剪混排字符串 (不切断 UTF-8 字符)
local function clip_mix(s, maxw)
  local out, w, k = {}, 0, 1
  while k <= #s do
    local b = s:byte(k)
    local n = (b >= 0xE0) and 3 or 1
    local ch = s:sub(k, k+n-1)
    local cw = app.mixw(ch)
    if w + cw > maxw then break end
    out[#out+1] = ch
    w = w + cw
    k = k + n
  end
  return table.concat(out)
end

function wrap_mix(s, maxw)
  local lines, cur, w = {}, "", 0
  local k = 1
  while k <= #s do
    local b = s:byte(k)
    local n = (b >= 0xE0) and 3 or 1
    local ch = s:sub(k, k+n-1)
    local cw = app.mixw(ch)
    if w + cw > maxw and cur ~= "" then
      lines[#lines+1] = cur; cur, w = "", 0
    end
    cur = cur .. ch; w = w + cw
    k = k + n
  end
  if cur ~= "" then lines[#lines+1] = cur end
  return lines
end

-- 24px 中英混排 (汉字 zh24 / ASCII 16x24) —— 标题专用, 界面只用 16px 与 24px 两档
local function mix24(x, y, s, inv)
  local i, n = 1, #s
  while i <= n do
    local b = s:byte(i)
    if b < 0x80 then
      app.text(x, y, s:sub(i, i), inv); x = x + 16; i = i + 1
    elseif b >= 0xF0 then
      app.zh24(x, y, s:sub(i, i+3), inv); x = x + 24; i = i + 4
    elseif b >= 0xE0 then
      app.zh24(x, y, s:sub(i, i+2), inv); x = x + 24; i = i + 3
    else
      app.zh24(x, y, s:sub(i, i+1), inv); x = x + 24; i = i + 2
    end
  end
  return x
end

local function mix24w(s)
  local w, i, n = 0, 1, #s
  while i <= n do
    local b = s:byte(i)
    if b < 0x80 then w = w + 16; i = i + 1
    elseif b >= 0xF0 then w = w + 24; i = i + 4
    elseif b >= 0xE0 then w = w + 24; i = i + 3
    else w = w + 24; i = i + 2 end
  end
  return w
end

