-- 启蒙引导: 第 1 关首次进入时讲**一个真正的数独技巧**(宫的隐性唯一), 不是操作说明。
--   "某个宫里已经填了 8 个数, 只剩一格 —— 那一格只能是缺的那个数。"
-- 第 1 关的题目由 tools/sudoku_gen.py 保证存在这样的宫 (has_box_single)。
local function first_naked_single()
  local cd = cand_map()
  for i = 1, 81 do
    if B.val[i] == 0 then
      local m = cd[i]
      if m ~= 0 and bitcnt(m) == 1 then return i, bitlist(m)[1] end
    end
  end
  return nil
end

local function first_box_single()
  for bi = 1, 9 do
    local u = UNITS[18 + bi]
    local e, n, mask = nil, 0, 0
    for _, i in ipairs(u) do
      local v = B.val[i]
      if v == 0 then e = i; n = n + 1
      elseif v >= 1 and v <= 9 then mask = mask | (1 << (v-1)) end
    end
    if n == 1 and e then
      for k = 1, 9 do
        if (mask & (1 << (k-1))) == 0 then return e, k end
      end
    end
  end
  return nil
end

