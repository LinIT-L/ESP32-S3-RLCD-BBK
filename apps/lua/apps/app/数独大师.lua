-- 供 tools/sudoku_test.py 在主机用 lupa 调用; 不参与设备运行逻辑。
function _selftest()
  local fail, n = {}, 0
  local function ck(cond, msg)
    n = n + 1
    if not cond then fail[#fail+1] = msg end
  end
  ck(#PUZZLE_DATA == 60, "题库不是 60 题")
  for lv, q in ipairs(PUZZLE_DATA) do
    ck(#q.p == 81 and #q.s == 81, "第" .. lv .. "题长度错")
    local diff = 0
    for i = 1, 81 do
      local a = tonumber(q.p:sub(i, i))
      if a and a ~= 0 and a ~= tonumber(q.s:sub(i, i)) then diff = diff + 1 end
    end
    ck(diff == 0, "第" .. lv .. "题与解答冲突")
  end
  ck(gain(0) == 3 and gain(1) == 2 and gain(2) == 1 and gain(3) == 0, "计分分档错")
  ck(gain(9) == 0, "计分 3 次以上错")
  -- 计分结算: 首次 1 分, 重玩 3 分只补 2 分
  local save_points, save_claimed = G.points, G.claimed
  local save_rec = G.rec[1]
  G.points, G.claimed = 0, 0
  G.rec[1] = { done=0, best=0, paid=1 }
  local score, award = 3, 3 - G.rec[1].paid
  if award < 0 then award = 0 end
  G.points = G.points + award
  G.rec[1].best = math.max(G.rec[1].best, score)
  G.rec[1].paid = math.max(G.rec[1].paid, score)
  ck(award == 2 and G.points == 2, "重玩补差额错")
  score, award = 1, 1 - G.rec[1].paid
  if award < 0 then award = 0 end
  ck(award == 0, "成绩更差扣分了")
  G.points, G.claimed, G.rec[1] = save_points, save_claimed, save_rec
  -- 存档字符串往返
  G.active_lv = 7; G.points = 42; G.skill.tip = 2
  local body = table.concat({ "M1", G.points, G.claimed, G.active_lv,
    G.skill.ex, G.skill.loc, G.skill.tip, 1, 0 }, "|")
  local s = pack("M", body)
  ck(unpack_save(s, "M") == body, "存档打包/解包错")
  ck(unpack_save(s .. "x", "M") == nil, "坏存档未拦截")
  ck(checksum("abc") == checksum("abc"), "校验和不确定")
  -- 冲突与候选: 用第 1 题起局
  if PUZZLE_DATA[1] then
    start_level(1, true)
    local given_n = 0
    for i = 1, 81 do if B.given[i] ~= 0 then given_n = given_n + 1 end end
    ck(given_n >= 40, "第 1 题给定数异常")
    local empty = 0
    for i = 1, 81 do if B.val[i] == 0 then empty = i; break end end
    ck(empty > 0, "第 1 题没有空格")
    if empty > 0 then
      local d = B.sol[empty]
      ck(not conflict(empty, d), "正确答案被判冲突")
      local wrong_d = (d % 9) + 1
      -- 构造一个同行冲突
      local r = (empty-1)//9
      for j = r*9+1, r*9+9 do
        if j ~= empty and B.val[j] ~= 0 then
          ck(conflict(empty, B.val[j]), "同行重复未判冲突")
          break
        end
      end
      ck((cand_of(empty) & (1 << (d-1))) ~= 0, "正确数字不在候选中")
      put_digit(empty, d)
      ck(B.val[empty] == d and not B.wrong[empty] and B.err == 0, "正确填写判定错")
      -- 找一个确定错误的数字 (与题解不同)
      local bad_i = 0
      for i = 1, 81 do if B.given[i] == 0 and B.val[i] == 0 then bad_i = i; break end end
      if bad_i > 0 then
        local bad = (B.sol[bad_i] % 9) + 1
        put_digit(bad_i, bad)
        ck(B.val[bad_i] == 0 and B.wrong[bad_i] ~= true and B.err == 1, "错误填写未计错")
        put_digit(bad_i, bad)
        ck(B.err == 2, "重复点同一错误格重复计错")
      end
    end
    -- 原始数字不可改 / 不可擦除
    local g0 = 0
    for i = 1, 81 do if B.given[i] ~= 0 then g0 = i; break end end
    if g0 > 0 then
      local keep = B.val[g0]
      put_digit(g0, (keep % 9) + 1)
      ck(B.val[g0] == keep, "原始题目数字被覆盖")
      erase_cell(g0)
      ck(B.val[g0] == keep, "原始题目数字被擦除")
    end
    -- 候选笔记: 手动增删 / 自动填充 / 清理 / 清除
    local e2 = 0
    for i = 1, 81 do if B.given[i] == 0 and B.val[i] == 0 then e2 = i; break end end
    if e2 > 0 then
      clear_notes()
      toggle_note(e2, 3)
      ck((B.notes[e2] & 4) ~= 0, "候选笔记添加失败")
      toggle_note(e2, 3)
      ck((B.notes[e2] & 4) == 0, "候选笔记删除失败")
      auto_notes()
      ck(B.notes[e2] == cand_of(e2), "自动候选不等于合法候选")
      clean_notes()
      ck(B.notes[e2] == (B.notes[e2] & cand_of(e2)), "清理不合法候选失败")
      clear_notes()
      ck(B.notes[e2] == 0, "清除全部候选失败")
      local before = B.cnt[B.sol[e2]]
      put_digit(e2, B.sol[e2])
      ck(B.cnt[B.sol[e2]] == before + 1, "填入后剩余数量未减少")
      erase_cell(e2)
      ck(B.val[e2] == 0 and B.cnt[B.sol[e2]] == before, "擦除后数量未恢复")
    end
    -- 技巧扫描: 结果必须来自真实算法, 等级不超已开放上限
    start_level(1, true)            -- 干净局面, 不让前面填入的数字干扰候选
    G.skill.tip = 4
    local sl = scan_techniques()
    ck(type(sl) == "table", "技巧扫描未返回表")
    local found_l1, shape_ok = false, true
    for _, it in ipairs(sl) do
      if it.lv == 1 then found_l1 = true end
      if not (it.name and it.desc and it.cells and #it.cells > 0
              and it.lv >= 1 and it.lv <= 4) then shape_ok = false end
    end
    ck(found_l1, "技巧扫描未发现 L1 技巧")
    ck(shape_ok, "技巧结果结构不完整")
    G.skill.tip = 1
    local sl1 = scan_techniques()
    local lv_ok = true
    for _, it in ipairs(sl1) do if it.lv > 1 then lv_ok = false end end
    ck(lv_ok, "Lv1 技巧扫描返回了高等级结果")
    -- 辅助技能: 升级即被动生效 (无按钮), 只高亮不改候选
    G.skill.ex, G.skill.loc = 3, 3
    local cntv, pick = {}, 41
    for i = 1, 81 do local v = B.val[i]; if v ~= 0 then cntv[v] = (cntv[v] or 0) + 1 end end
    for i = 1, 81 do
      local v = B.val[i]
      if v ~= 0 and (cntv[v] or 0) >= 2 then pick = i; break end
    end
    B.sel = pick
    local nb0 = B.notes[pick]
    local hl = highlight_map()
    ck(hl[pick] == nil, "选中格自身不应被高亮")
    local sr, sc, sb = (pick-1)//9, (pick-1)%9, BOX_ID[pick]
    local row_hit, col_hit, box_hit, same_hit = false, false, false, false
    for i = 1, 81 do
      if i ~= pick and hl[i] then
        if (i-1)//9 == sr then row_hit = true end
        if (i-1)%9 == sc then col_hit = true end
        if BOX_ID[i] == sb then box_hit = true end
        if hl[i] == "deep" and B.val[i] == B.val[pick] then same_hit = true end
      end
    end
    ck(row_hit and col_hit and box_hit, "排除 Lv3 未覆盖行/列/宫")
    ck(same_hit, "定位 Lv3 未标记相同数字")
    ck(B.notes[pick] == nb0, "辅助高亮改动了候选笔记")
    G.skill.ex, G.skill.loc = 1, 0
    local hl1 = highlight_map()
    local c1_hit = false
    for i = 1, 81 do
      if i ~= pick and (i-1)%9 == sc and hl1[i] then c1_hit = true end
    end
    ck(c1_hit, "关联高亮未覆盖同列")
    G.skill.ex, G.skill.loc = 3, 3
    -- 技能购买: 扣费一次, 章节门禁不扣分
    G.points = 200
    G.skill.ex = 0
    G.shop_sel = 1
    do_buy()
    ck(G.skill.fill == 1 and G.points == 195, "技能购买扣费错")
    do_buy()
    ck(G.points == 195, "未解锁章节仍扣费")
    -- 数字剩余数量为 0 时从左侧隐藏, 其余按钮重排
    local vis0 = visible_digits()
    B.cnt[5] = 9
    local vis1 = visible_digits()
    local still = false
    for _, d in ipairs(vis1) do if d == 5 then still = true end end
    ck(#vis1 == #vis0 - 1 and not still, "数量满 9 的数字未隐藏")
    recount()
    ck(#visible_digits() == #vis0, "重算后数字按钮未恢复")
    -- 存档: 写入 -> 破坏内存 -> 读回
    G.points = 17
    start_level(5)
    local s5 = 0
    for i = 1, 81 do if B.given[i] == 0 then s5 = i; break end end
    put_digit(s5, B.sol[s5])
    B.err = 2
    B.notes[s5] = 0
    save_all()
    local expect = B.sol[s5]
    B.val[s5], G.points, G.skill.tip = 0, 0, 0
    load_meta()
    local okload = load_game()
    ck(okload and B.lv == 5 and B.val[s5] == expect and B.err == 2, "存档局面恢复失败")
    ck(G.points == 17, "存档积分恢复失败")
    ck(unlocked(1), "第 1 关应解锁")
