--   避免每帧白白拼出 4 个临时字符串喂给 GC。
local function elapsed_sec()
  local sec = (app.millis() - (B.t0 or 0)) // 1000
  if sec < 0 then sec = 0 end
  if sec > 5999 then sec = 5999 end
  return sec
end
local function elapsed_str()
  local sec = elapsed_sec()
  return two_digits(sec // 60) .. ":" .. two_digits(sec % 60)
end

-- 秒变化只局部重画右栏这一行: 不置 G.dirty ⇒ 不整屏重绘棋盘 (沿用 G.dirty 约定)
local function draw_right_time()
  local sec = elapsed_sec()
  local str = two_digits(sec // 60) .. ":" .. two_digits(sec % 60)
  G.last_clock, G.last_sec = str, sec
  app.fill(RIGHT_X+1, R_TIME_Y, W-1, R_TIME_Y+18, WH)
  app.mixc(R_CX, R_TIME_Y, str)
end

local R_BTN_R = 6
-- 圆角描边/填充 (1bpp 自绘, r 角用 4 段短斜线, 不铺整行导致顶部变粗)
local function round_outline(x0, y0, x1, y1, r, c)
  app.hline(x0+r, x1-r, y0, c); app.hline(x0+r, x1-r, y1, c)
  app.vline(x0, y0+r, y1-r, c); app.vline(x1, y0+r, y1-r, c)
  for k = 1, r-1 do
    local t = r - k
    app.px(x0+k, y0+t-1, c); app.px(x1-k, y0+t-1, c)
    app.px(x0+k, y1-t+1, c); app.px(x1-k, y1-t+1, c)
  end
end
local function round_fill(x0, y0, x1, y1, r, c)
  for yy = y0, y1 do
    local dy = math.min(yy-y0, y1-yy)
    local inset = (dy < r) and (r - dy - 1) or 0
    app.hline(x0+inset, x1-inset, yy, c)
  end
end

