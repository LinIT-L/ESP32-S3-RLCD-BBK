  G.hsel, G.hdx = 1, 0
  G.last_save = app.millis()
  set_page("home")
  G.dirty = true
end

function poll()
  -- 系统弹窗结果 (技能商店 / 设置 都走弹窗)
  local r = app.dlg.result()
  if r ~= nil then
    local kind = G.dlg_kind
    G.dlg_kind = nil
    if kind == "shop" and r >= 1 then
      G.shop_sel = clamp(r, 1, #SKILLS)
      local p0 = G.points
      do_buy()
      if G.points < p0 then G.dlg_reopen = "shop" end   -- 买成功才重开列表
    elseif kind == "settings" and r >= 1 then
      if r == 1 then G.sfx = not G.sfx; G.save_dirty = true; G.dlg_reopen = "settings"
      elseif r == 2 then G.vib = not G.vib; G.save_dirty = true; G.dlg_reopen = "settings"
      elseif r == 3 then G.restricted = not G.restricted; G.save_dirty = true; G.dlg_reopen = "settings"
      elseif r == 4 then set_page("datamenu") end
    end
    G.dirty = true
  end
  if G.dlg_reopen then
    local k = G.dlg_reopen
    G.dlg_reopen = nil
    if k == "shop" then open_shop_dlg() else open_settings_dlg() end
  end
  -- 触摸: 按下沿 / 抬起沿, 长按 >=480ms
  local x, y = app.touch()
  if type(x) == "number" then
    if not T.down then
      T.down, T.sx, T.sy, T.moved, T.hold, T.drag = true, x, y, false, 0, false
    end
    local dx, dy = x - T.sx, y - T.sy
    if math.abs(dx) > 12 or math.abs(dy) > 12 then T.moved = true end
    -- 首页: 横向跟手拖动卡片 (只重画卡片带, 见 draw_home_cards)
    if G.page == "home" and math.abs(dx) > 10 and math.abs(dx) > math.abs(dy) then
      T.drag = true
      if G.hdx ~= dx or not G.hdrag then
        G.hdx, G.hdrag = dx, true
        G.dirty = true
      end
    end
    T.hold = app.touch_hold()
  elseif T.down then
    local long = T.hold >= 480
    if T.drag and G.page == "home" then
      -- 松手吸附: 拖过 1/3 张卡宽就翻页, 否则回弹
      local th = home_step() // 3
      local n = #home_cards()
      if G.hdx <= -th and G.hsel < n then
        G.hsel = G.hsel + 1; G.hdx = G.hdx + home_step()
      elseif G.hdx >= th and G.hsel > 1 then
        G.hsel = G.hsel - 1; G.hdx = G.hdx - home_step()
      end
      G.dirty = true
    elseif not T.moved then
      local ok, err = pcall(on_tap, T.sx, T.sy, long)
      if not ok then app.log("tap error: " .. tostring(err)) end
    end
    T.down, T.drag = false, false
  end
  -- 首页回弹动画: 只重画卡片带; 步长放大到 40px ⇒ 常规偏移 1~3 帧就归位
  if G.page == "home" and not T.down and G.hdx ~= 0 then
    local sp = 40
    if math.abs(G.hdx) <= sp then G.hdx = 0
    elseif G.hdx > 0 then G.hdx = G.hdx - sp
    else G.hdx = G.hdx + sp end
    G.hdrag = (G.hdx ~= 0)          -- 归位那一帧走全量重绘, 免得留下拖动期没画的圆点/台阶
    G.dirty = true
  elseif G.hdrag then
    G.hdrag = false
    G.dirty = true
  end
  -- 自动填充(技能): 落子后跑一轮级联填充
  if G.fill_pending then
    G.fill_pending = false
    if (G.skill.fill or 0) > 0 and not G.completed then
      local nf = auto_fill_chain()
      if nf > 0 then
        G.dirty = true
        toast("自动填充 +" .. nf, 700)
      end
    end
  end
  if G.save_dirty and (app.millis() - G.last_save) >= 3000 then save_all() end
  if G.toast_until > 0 and app.millis() > G.toast_until then
    G.toast_until = 0
    G.dirty = true
  end
  -- ★ 本关已用时间: 秒变化只重画右栏那一行, 不置 G.dirty ⇒ 棋盘不重绘
  --   (2026-11-22: 比整数秒而不是比字符串, 每帧零分配)
  if G.page == "game" and elapsed_sec() ~= (G.last_sec or -1) then draw_right_time() end
end

