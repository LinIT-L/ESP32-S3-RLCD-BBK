-- -------------------------------- 触摸 ----------------------------------
local function in_rect(x, y, x0, y0, x1, y1)
  return x >= x0 and x <= x1 and y >= y0 and y <= y1
end

local function menu_index(x, y)
  local y0, rh = menu_rects()
  if x < 0 or x > W then return 0 end
  local k = ((y - y0) // rh) + 1
  if k >= 1 and k <= #G.items then return k end
  return 0
end

local function board_hit(x, y)
  if x < BX or x >= BX+BS or y < BY or y >= BY+BS then return 0 end
  local c = (x - BX) * 9 // BS
  local r = (y - BY) * 9 // BS
  -- 33/34 交替的边界修正 (最多差 1)
  while c > 0 and x < BX + EDG[c] do c = c - 1 end
  while c < 8 and x >= BX + EDG[c+1] do c = c + 1 end
  while r > 0 and y < BY + EDG[r] do r = r - 1 end
  while r < 8 and y >= BY + EDG[r+1] do r = r + 1 end
  return r*9 + c + 1
end

-- ★ 2026-11-08: 卡片是紧凑重排的, 命中判定必须用**同一套 left_geom**,
--   否则点到的位置和看到的那张卡对不上(旧版按固定槽位算, 重排后必错位)。
local function left_hit(x, y)
  if x >= LEFT_W then return 0 end
  local vis, step, n = left_geom()
  local k = (y // step) + 1
  if k < 1 then k = 1 end
  if k > n then k = n end
  return vis[k] or 0
end

-- 点左侧数字: 单击=待填/填入; 长按=给选中空格加/去候选 (替代原来的笔记模式按钮)
local function tap_digit(d, long)
  if long then
    if B.sel >= 1 and B.val[B.sel] == 0 then
      toggle_note(B.sel, d)
      toast(((B.notes[B.sel] or 0) & (1 << (d-1))) ~= 0 and "加候选" or "去候选", 700)
    else
      toast("先选空格", 900)
    end
    return
  end
  if B.mode == "note" and B.sel >= 1 and B.val[B.sel] == 0 then
    toggle_note(B.sel, d)
    return
  end
  -- ★★ 2026-11-08 linit「点数字、再点空格必须一次填入」:
  --   两个方向都只花一次点击 ——
  --     ① 先点数字(没选空格) → 进入待填, 再点空格即填入 (见 tap_cell);
  --     ② 先点空格(已选中空位) → 再点数字 = **直接确认填入**, 不再要求回去补点一次空格。
  --   这是"第一次点击只选中、第二次才填"的真正原因: 旧版点数字一律把 B.sel 清 0,
  --   已经选好的空格被丢掉, 用户必须再点一次那个格子。
  if B.sel >= 1 and B.sel <= 81 and B.val[B.sel] == 0 then
    B.pend = d
    put_digit(B.sel, d)          -- 填错会被 put_digit 拒绝并提示, pend 保留可继续尝试
    B.sel = 0
    G.dirty = true
    return
  end
  B.pend = (B.pend == d) and 0 or d
  B.sel = 0
  G.dirty = true
end

-- 点棋盘: 单击=选中(或按待填数字填入); 长按=擦除该格 (替代原来的擦除模式按钮)
local function tap_cell(i, long)
  if long then
    B.sel = i
    erase_cell(i)
    G.dirty = true
    return
  end
  B.sel = i
  -- ★ 2026-11-08 linit 要求的交互: 左侧先选数字(反色=选择中), 再点**空格**即确认输入。
  --   填完不清 pend —— 可以连续点多个空格填同一个数字; 再点该数字或点别处才取消。
  if B.pend > 0 and i >= 1 and i <= 81 then
    if B.val[i] == 0 then
      put_digit(i, B.pend)
    else
      toast("这格已有数字", 700)
    end
  end
  G.dirty = true
end

local function on_tap(x, y, long)
  if G.page == "game" then
    if G.tut then
      G.tut = nil
      G.tut_seen = true
      -- ★ 2026-11-08 linit: 关掉浮层后**不预选**格子/数字 —— 教学不替玩家落子,
      --   也避免"预选了格子, 玩家点错数字直接被判错扣分"。
      local i, d = first_box_single()
      if not i then i, d = first_naked_single() end
      if i then toast("找个只剩一格的宫, 缺 " .. d, 2000) end
      G.dirty = true
      return
    end
    if x >= RIGHT_X then
      if x >= R_BTN_X and x <= R_BTN_X + R_BTN_W - 1
         and y >= R_BTN_Y and y <= R_BTN_Y + R_BTN_H - 1 then
        if long then set_page("notemenu"); return end   -- 长按: 候选批量操作
        B.mode = (B.mode == "note") and "normal" or "note"
        B.pend = 0
        toast(B.mode == "note" and "笔记模式" or "普通模式", 800)
        G.dirty = true
      end
      return
    end
    local d = left_hit(x, y)
    if d > 0 then tap_digit(d, long); return end
    local i = board_hit(x, y)
    if i > 0 then tap_cell(i, long); return end
    return
  end
  -- 底部台阶: 左=设置 右=技能商店 中=返回 (非游戏页统一)
  if page_has_nav(G.page) then
    local nb = nav_hit(x, y)
    if nb == 1 then open_settings_dlg(); return end
    if nb == 2 then open_shop_dlg(); return end
    if nb == 3 then
      local bp = nav_back_page()
      if bp then set_page(bp) end
      return
    end
  end
  if G.page == "chapters" then
    local ch = chapter_hit(x, y)
    if ch == 0 then return end
    if not chapter_unlocked(ch) then toast("本章未解锁"); G.dirty = true; return end
    G.chapter = ch
    set_page("levels")
  elseif G.page == "levels" then
    local k = level_hit(x, y)
    if k >= 1 then
      G.sel = k
      local lv = (G.chapter-1)*10 + k
      if not unlocked(lv) then toast("本关未解锁"); G.dirty = true; return end
      G.mode_endless = false
      start_level(lv)
      if lv == 1 and G.rec[1].done == 0 and not G.tut_seen then G.tut = 1 end
      auto_fill_chain()          -- 有自动填充技能: 进关就先填一轮
      set_page("game")
    end
    return
  elseif G.page == "result" then
    local y0, rh = 166, 34
    local k = ((y - y0) // rh) + 1
    if k >= 1 and k <= #G.items then G.sel = k; do_item(G.items[k].id) end
  elseif G.page == "endgame_detail" or G.page == "classic_detail" then
    if in_rect(x, y, 12, 250, 180, 290) then do_item("sp_start")
    elseif in_rect(x, y, W-180, 250, W-12, 290) then do_item("sp_back") end
    return
  else
    if G.page == "home" then
      local k = home_hit(x, y)
      if k == 0 then return end
      if k == G.hsel then
        do_item(home_cards()[k].id)
      else                                  -- 点两侧的卡片: 先切焦点
        G.hsel, G.hdx = k, 0
        beep(600, 20)
        G.dirty = true
      end
      return
    end
    local k = menu_index(x, y)
    if k > 0 then
      G.sel = k
      do_item(G.items[k].id)
    end
  end
end

local function handle_key(a)
  if a == A_BACK then
    if G.page == "game" then
      set_page("home"); G.save_dirty = true
      return true
    elseif G.page == "home" then
      return false                    -- 交框架弹「退出程序?」
    else
      if G.page == "levels" then set_page("chapters")
      elseif G.page == "datamenu" then set_page("home")   -- 设置已改成弹窗, 不再有独立设置页
      elseif G.page == "notemenu" then set_page("game")
      elseif G.page == "endgame_detail" or G.page == "classic_detail" then
        set_page(G.detail and (G.detail.kind == "endgame" and "endgame_list" or "classic_list") or "home")
      else set_page("home") end
      return true
    end
  end
  if G.page == "game" then
    if a == app.UP or a == app.DOWN or a == app.LEFT or a == app.RIGHT then
      local i = B.sel
      if i == 0 then i = 1 end
      local r, c = (i-1)//9, (i-1)%9
      if a == app.UP then r = (r+8)%9
      elseif a == app.DOWN then r = (r+1)%9
      elseif a == app.LEFT then c = (c+8)%9
      else c = (c+1)%9 end
      B.sel = r*9 + c + 1
      G.dirty = true
      return true
    end
    if a == app.OK then B.pend = 0; refresh_tip(); G.dirty = true; return true end
    return true
  end
  if G.page == "home" then
    local n = #home_cards()
    if a == app.LEFT or a == app.UP then
      G.hsel = math.max(1, G.hsel - 1); G.hdx = 0; G.dirty = true; return true
    end
    if a == app.RIGHT or a == app.DOWN then
      G.hsel = math.min(n, G.hsel + 1); G.hdx = 0; G.dirty = true; return true
    end
    if a == app.OK then do_item(home_cards()[G.hsel].id); return true end
    return true
  end
  if G.page == "chapters" then
    if a == app.UP or a == app.DOWN then G.sel = ((G.sel - 1 + 2) % 6) + 1
    elseif a == app.LEFT or a == app.RIGHT then G.sel = (G.sel % 6) + 1 end
    G.dirty = true
    return true
  end
  if G.page == "levels" then
    if a == app.UP then G.sel = math.max(1, G.sel - 2)
    elseif a == app.DOWN then G.sel = math.min(11, G.sel + 2)
    elseif a == app.LEFT then G.sel = math.max(1, G.sel - 1)
    elseif a == app.RIGHT then G.sel = math.min(11, G.sel + 1) end
    G.dirty = true
    return true
  end
  if a == app.UP or a == app.LEFT then
    G.sel = (G.sel - 2) % #G.items + 1; G.dirty = true; return true
  end
  if a == app.DOWN or a == app.RIGHT then
    G.sel = G.sel % #G.items + 1; G.dirty = true; return true
  end
  if a == app.OK then
    if G.items[G.sel] then do_item(G.items[G.sel].id) end
    return true
  end
  return true
end

