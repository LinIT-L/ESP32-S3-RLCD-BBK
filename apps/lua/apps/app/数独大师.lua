local function checksum(s)
  local v = 0
  for i = 1, #s do v = (v * 31 + s:byte(i)) % 1000003 end
  return v
end

local function pack(tag, body)
  return tag .. "|" .. body .. "|" .. checksum(body)
end

local function unpack_save(s, tag)
  if type(s) ~= "string" then return nil end
  -- 头 tag / 尾校验和 / 中间 body (body 自身允许含 '|')
  local p1 = s:find("|", 1, true)
  if not p1 then return nil end
  local head = s:sub(1, p1 - 1)
  local last = 1
  for i = 1, #s do if s:sub(i, i) == "|" then last = i end end
  local body = s:sub(p1 + 1, last - 1)
  local sum = s:sub(last + 1)
  if head ~= tag or not sum:match("^%d+$") then return nil end
  if tonumber(sum) ~= checksum(body) then return nil end
  return body
end

local function split(s, sep)
  local out = {}
  for part in (s .. sep):gmatch("(.-)" .. sep) do out[#out+1] = part end
  return out
end

