-- ============ 底部「台阶」导航 (照搬网络检测页的盖子/谷线造型) ============
-- 左键=设置, 右键=技能商店, 中间谷线区放一行信息 (子页前面加 ‹ 返回, 点中间=返回)。
local NAV_Y   = 277            -- 按键文字顶
local NAV_LID = NAV_Y - 4      -- 左右横杠高度
local NAV_VAL = H - 6          -- 谷线 (屏幕最底)
local NAV_LX  = 10             -- 左键左缘
local NAV_RX  = W - 10         -- 右键右缘

local function nav_geom()
  local lw = app.mixw("设置")
  local rw = app.mixw("技能商店")
  local lend   = NAV_LX + lw + 10      -- 左横杠终点
  local rstart = NAV_RX - rw + 1 - 10  -- 右横杠起点
  local slope  = NAV_VAL - NAV_LID
  return lw, rw, lend, rstart, slope
end

local function draw_bottom_nav(mid)
  local lw, rw, lend, rstart, slope = nav_geom()
  app.mix(NAV_LX, NAV_Y, "设置")
  app.mix(NAV_RX - rw + 1, NAV_Y, "技能商店")
  app.hline(0, lend, NAV_LID, BK)
  app.hline(rstart, W-1, NAV_LID, BK)
  local vl, vr = lend + slope, rstart - slope
  if vl < vr then app.hline(vl, vr, NAV_VAL, BK) end
  for d = 0, slope do
    app.px(lend + d, NAV_LID + d, BK)
    app.px(rstart - d, NAV_LID + d, BK)
  end
  if mid and mid ~= "" and vl < vr then
    local mw = app.mixw(mid)
    local mx = (vl + vr) // 2 - mw // 2
    if mx < vl + 4 then mx = vl + 4 end
    if mx + mw > vr - 4 then mx = vr - 4 - mw end
    if mx >= vl then app.mix(mx, NAV_Y, mid) end
  end
end

-- 1=设置 2=技能商店 3=中间(返回) 0=没点到
local function nav_hit(x, y)
  if y < NAV_LID - 3 then return 0 end
  local lw, rw, lend, rstart = nav_geom()
  if x <= NAV_LX + lw + 8 then return 1 end
  if x >= NAV_RX - rw - 8 then return 2 end
  return 3
end

