function start_level(lv, restoring)
  local q = PUZZLE_DATA[lv]
  if not q then toast("题库未就绪"); return false end
  B.lv = lv
  B.t0 = app.millis()              -- ★ 本关已用时间从进关这一刻起算
  B.given, B.val, B.who, B.wrong, B.lastbad, B.notes, B.sol = {}, {}, {}, {}, {}, {}, {}
  for i = 1, 81 do
    local g = tonumber(q.p:sub(i, i)) or 0
    B.given[i] = g
    B.val[i] = g
    B.who[i] = (g ~= 0) and 1 or 0
    B.wrong[i] = false
    B.lastbad[i] = 0
    B.notes[i] = 0
    B.sol[i] = tonumber(q.s:sub(i, i)) or 0
  end
  B.manual = {}
  B.err, B.sel, B.pend, B.mode = 0, 0, 0, "normal"
  B.hl_ex, B.hl_loc = nil, nil
  B.restricted = G.restricted
  B.special = nil
  B.special_idx = 0
  G.tip = nil
  recount()
  auto_fill_notes()
  refresh_tip()
