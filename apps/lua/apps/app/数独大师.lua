    G.rec[1] = { done=0, best=0, paid=0 }
    G.points = 0
    local function solve(lv, make_err)
      start_level(lv)
      if make_err then
        local bi = 0
        for i = 1, 81 do if B.given[i] == 0 then bi = i; break end end
        if bi > 0 then put_digit(bi, (B.sol[bi] % 9) + 1) end
      end
      for i = 1, 81 do
        if B.given[i] == 0 then
          put_digit(i, B.sol[i])
          if B.lv == 0 then break end
        end
      end
    end
    solve(1, false)
    ck(G.rec[1].done == 1 and G.rec[1].paid == 3 and G.points == 3,
       "0 错误通关应结算 3 分")
    ck(G.page == "result", "通关后未进入结算页")
    ck(unlocked(2), "通关后未解锁下一关")
    solve(1, true)
    ck(G.points == 3, "重玩成绩更差却扣了分")
    G.rec[1] = { done=1, best=1, paid=1 }
    G.points = 0
    solve(1, false)
    ck(G.points == 2 and G.rec[1].paid == 3, "重玩更好未补发差额 2 分")

    -- 无尽模式: 通关一层 -> 层数/分数/最佳更新, 且不写章节记录
    local keep_done = G.rec[1].done
    G.mode_endless = true
    G.endless = { n = 0, score = 0, last = 0 }
    G.endless_best = 0
    start_level(1)
    for i = 1, 81 do
      if B.given[i] == 0 then
        put_digit(i, B.sol[i])
        if G.endless.n > 0 or B.lv == 0 then break end
      end
    end
    ck(G.endless.n == 1 and G.endless.score == 3 and G.endless_best == 1,
       "无尽模式结算错")
    -- 无尽是连打模式: 通一层直接续下一题, 不弹结算页
    ck(G.page == "game" and B.lv > 0, "无尽模式应直接续下一题")
    ck(G.rec[1].done == keep_done, "无尽模式不应写章节记录")
    G.mode_endless = false
  end
  return { ok = (#fail == 0), count = n, fail = fail }
end

