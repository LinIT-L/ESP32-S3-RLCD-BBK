  for i = 1, 81 do
    if hl[i] == "dots" then
      local cx, cy = cell_xy(i); light_cell(cx, cy, cell_w(i), cell_h(i))
    end
  end
  -- 2) 相同数字: 反色 + 白点 (深灰), 覆盖上面的浅灰
  for i = 1, 81 do
    if hl[i] == "deep" and i ~= B.sel then
      local cx, cy = cell_xy(i); deep_cell(cx, cy, cell_w(i), cell_h(i))
    end
  end
  -- 3) 网格: 内部 1px 实线, 宫线/外框 2px
  for k = 1, 8 do
    if k % 3 ~= 0 then
      local x, y = BX + EDG[k], BY + EDG[k]
      app.vline(x, BY, BY + BS - 1, BK)
      app.hline(BX, BX + BS - 1, y, BK)
    end
  end
  for k = 0, 9, 3 do
    local x = BX + EDG[k]
    local y = BY + EDG[k]
    if k == 9 then x, y = BX + BS - 2, BY + BS - 2 end   -- 右边/下边向内 2px
    app.vline(x, BY, BY + BS - 1, BK);   app.vline(x+1, BY, BY + BS - 1, BK)
    app.hline(BX, BX + BS - 1, y, BK);   app.hline(BX, BX + BS - 1, y+1, BK)
  end
  -- 4) 技巧结果: 相关格双框
  if G.tip then
    for _, i in ipairs(G.tip.cells) do
      if i ~= B.sel then
        local cx, cy = cell_xy(i)
        local cw, ch = cell_w(i), cell_h(i)
        app.rect(cx+1, cy+1, cx+cw-2, cy+ch-2, BK)
        app.rect(cx+3, cy+3, cx+cw-4, cy+ch-4, BK)
      end
    end
  end
  -- 5) 格内容 (选中格留到最后整格反色)
  for i = 1, 81 do
    if i ~= B.sel then
      local cx, cy = cell_xy(i)
      local v = B.val[i]
      if B.wrong[i] and v ~= 0 then
        local cw, ch = cell_w(i), cell_h(i)
        app.fill(cx+1, cy+1, cx+cw-2, cy+ch-2, BK)
        app.textt(cx+8, cy+4, tostring(v), true)
        for k = 0, 4 do
          app.px(cx+cw-11+k, cy+ch-11+k, WH)
          app.px(cx+cw-7-k, cy+ch-11+k, WH)
        end
      elseif v ~= 0 then
        local inv = (hl[i] == "deep")
        if B.who[i] == 1 then app.textt(cx+8, cy+4, tostring(v), inv)    -- 原始 16x24
        else app.textt(cx+8, cy+4, tostring(v), inv) end               -- 玩家 12x18
      else
        local nm = B.notes[i] or 0
        local fm, em = 0, 0
        local need_cand = false
        if G.skill.tip <= 0 and G.hs and G.hs[i] then fm = fm | G.hs[i]; need_cand = true end
        if G.tip then
          fm = fm | (G.tip.focus[i] or 0)
          em = em | (G.tip.elim[i] or 0)
          if fm ~= 0 or em ~= 0 then need_cand = true end
        end
        -- ★ 2026-11-22: 原来每格现算一次 cand_of(20 peer); 改共享缓存后同一帧只算一遍全盘
        if need_cand then nm = cand_map()[i] | nm end
        if nm ~= 0 then draw_notes(i, nm, fm, em, false) end
      end
    end
  end
  -- 6) 选中格: 整格反色 (最后画, 覆盖网格)
  if B.sel >= 1 and B.sel <= 81 then
    local cx, cy = cell_xy(B.sel)
    local cw, ch = cell_w(B.sel), cell_h(B.sel)
    app.fill(cx, cy, cx+cw-1, cy+ch-1, BK)
    local v = B.val[B.sel]
    if v ~= 0 then
      if B.who[B.sel] == 1 then app.textt(cx+8, cy+4, tostring(v), true)
      else app.textt(cx+8, cy+4, tostring(v), true) end
      if B.wrong[B.sel] then
        for k = 0, 4 do
          app.px(cx+cw-11+k, cy+ch-11+k, WH)
          app.px(cx+cw-7-k, cy+ch-11+k, WH)
        end
      end
    else
      local m = cand_map()[B.sel] | (B.notes[B.sel] or 0)
      if m ~= 0 then
        if bitcnt(m) == 1 then
          app.textt(cx+8, cy+4, tostring(bitlist(m)[1]), true)
        else
          draw_notes(B.sel, m, 0, 0, true)
        end
      end
    end
  end
end

