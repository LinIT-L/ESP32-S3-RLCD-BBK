local function draw_notes(i, mask, focus, elim, white)
  local cx, cy = cell_xy(i)
  for d = 1, 9 do
    if (mask & (1 << (d-1))) ~= 0 then
      local col, row = (d-1)%3, (d-1)//3
      local nx, ny = cx + 2 + col*11, cy + 1 + row*11
      if white then
        draw_mini_white(nx, ny, d)
      elseif (elim & (1 << (d-1))) ~= 0 then
        draw_mini_x(nx, ny)
      elseif (focus & (1 << (d-1))) ~= 0 then
        draw_mini(nx, ny, d, true)
      else
        draw_mini(nx, ny, d, false)
      end
    end
  end
end

-- 关联高亮: 技能升级即**被动生效**, 不需要手动开启 (技能是加速, 不是作弊)
-- 返回 [i] = "deep"(相同数字: 反色+白点) / "dots"(行/列/宫关联: 菱形浅灰)
-- 错误检查(技能): 该格数字是否与同伴重复(按等级决定查行/列/宫)
local function conflict_here(i)
  local lv = G.skill.ex or 0
  local v = B.val[i]
  if lv <= 0 or v == 0 then return false end
  local r, c, bx = (i-1)//9, (i-1)%9, BOX_ID[i]
  for _, j in ipairs(PEER[i]) do
    if B.val[j] == v then
      local jr, jc, jb = (j-1)//9, (j-1)%9, BOX_ID[j]
      if (lv >= 1 and jr == r) or (lv >= 2 and jc == c) or (lv >= 3 and jb == bx) then
        return true
      end
    end
  end
  return false
end

-- 数字定位(技能): 某数字在本单元里只剩一个可放位置(隐性单) ⇒ 标记该位置
-- 结果按棋盘版本号缓存 —— 每帧现算是 27 单元×9 数字×9 格×cand_of(20 peer), 太慢
local s_loc_gen, s_loc_t = -1, {}
local function loc_marks()
  local lv = G.skill.loc or 0
  if lv <= 0 then return s_loc_t end
  if s_loc_gen == B.gen then return s_loc_t end
  local t = {}
  local cd = cand_map()
  for ui, u in ipairs(UNITS) do
    local k = unit_kind(ui)
    local allow = (k == 3 and lv >= 1) or (k == 1 and lv >= 2) or (k == 2 and lv >= 3)
    if allow then
      local has = {}
      for _, i in ipairs(u) do
        local v = B.val[i]
        if v ~= 0 then has[v] = true end
      end
      for d = 1, 9 do
        if not has[d] then
          local spot, cnt = nil, 0
          local mask = 1 << (d-1)
          for _, i in ipairs(u) do
            if B.val[i] == 0 and (cd[i] & mask) ~= 0 then cnt = cnt + 1; spot = i end
          end
          if cnt == 1 and spot then t[spot] = true end
        end
      end
    end
  end
  s_loc_gen, s_loc_t = B.gen, t
  return t
end

-- ★ 2026-11-22: 复用同一张表 —— 全量重绘每帧都调它, 原来每次新建 81 项的表
--   等于每帧制造一份垃圾, GC 抖动会直接体现在落子手感上。
local s_hl = {}
local function highlight_map()
  for i = 1, 81 do s_hl[i] = nil end
  local m = s_hl
  local sel = B.sel
  local d = B.pend
  if d == 0 then
    if sel < 1 or sel > 81 then return m end
    d = B.val[sel]
  end
  local sel_ok = (sel >= 1 and sel <= 81)

  -- 1) 棋盘有选中格时: 它的行/列/九宫变灰
  if sel_ok then
    local sr, sc, sb = (sel-1)//9, (sel-1)%9, BOX_ID[sel]
    for i = 1, 81 do
      if i ~= sel then
        local ir, ic = (i-1)//9, (i-1)%9
        if ir == sr or ic == sc or BOX_ID[i] == sb then m[i] = "dots" end
      end
    end
  end

  -- 2) 当前数字(B.pend 优先)在全盘的每一处: 反色; 并且**它们的行/列/九宫也变灰**
  --    linit: "选择的数字, 其他同数字也要横竖加九格变灰"
  if d ~= 0 then
    local rows, cols, boxes = {}, {}, {}
    for i = 1, 81 do
      if B.val[i] == d then
        if i ~= sel then m[i] = "deep" end
        rows[(i-1)//9]   = true
        cols[(i-1)%9]    = true
        boxes[BOX_ID[i]] = true
      end
    end
    for j = 1, 81 do
      if j ~= sel and m[j] == nil then
        if rows[(j-1)//9] or cols[(j-1)%9] or boxes[BOX_ID[j]] then m[j] = "dots" end
      end
    end
  end
  return m
end

-- 选中的格子若是空格, 显示它的合法候选 (相当于"裸单"提示)
local function draw_board()
  local hl = highlight_map()
