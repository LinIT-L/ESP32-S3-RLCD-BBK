-- 12px 混合小字: 汉字用 zhsm(12x12), ASCII 用 texts(8x12)。
-- 布局用; 需要和 16px 正文区分层次时用它, 而不是 mix。
local function smix(x, y, str, inv)
  local i, n = 1, #str
  while i <= n do
    local b = str:byte(i)
    if b < 0x80 then
      app.texts(x, y, str:sub(i, i), inv)
      x = x + 8
      i = i + 1
    elseif b >= 0xF0 then
      app.zhsm(x, y, str:sub(i, i+3), inv); x = x + 12; i = i + 4
    elseif b >= 0xE0 then
      app.zhsm(x, y, str:sub(i, i+2), inv); x = x + 12; i = i + 3
    else
      app.zhsm(x, y, str:sub(i, i+1), inv); x = x + 12; i = i + 2
    end
  end
  return x
end

local function smixw(str)
  local w, i, n = 0, 1, #str
  while i <= n do
    local b = str:byte(i)
    if b < 0x80 then w = w + 8; i = i + 1
    elseif b >= 0xF0 then w = w + 12; i = i + 4
    elseif b >= 0xE0 then w = w + 12; i = i + 3
    else w = w + 12; i = i + 2 end
  end
  return w
end

-- 12px 小字 + 宽度截断: 超出 maxw 就停, 不画到棋盘上
local function smix_clip(x, y, str, maxw, inv)
  local i, n, cx = 1, #str, x
  while i <= n do
    local b = str:byte(i)
    local w, len
    if b < 0x80 then w, len = 8, 1
    elseif b >= 0xF0 then w, len = 12, 4
    elseif b >= 0xE0 then w, len = 12, 3
    else w, len = 12, 2 end
    if cx + w > maxw then break end
    smix(cx, y, str:sub(i, i+len-1), inv)
    cx = cx + w
    i = i + len
  end
end

-- 16px 混合字 + 宽度截断: 汉字 16px / ASCII 8px, 超宽就停
