  return true
end

function finish_level()
  local lv = B.lv
  -- 经典残局 / 名题: 不写主线 rec/积分, 仅记录通关掩码防重复领取
  if B.special then
    local full, correct = true, true
    for k = 1, 81 do
      if B.val[k] == 0 then full = false end
      if B.val[k] ~= B.sol[k] then correct = false end
    end
    if not full then toast("棋盘尚未完成。", 1500); G.dirty = true; return end
    if not correct then toast("答案不正确，请自行检查。", 1800); G.dirty = true; return end
    if B.special == "endgame" then
      G.eg_done = (G.eg_done or 0) | (1 << (B.special_idx - 1))
    else
      G.cl_done = (G.cl_done or 0) | (1 << (B.special_idx - 1))
    end
    G.save_dirty = true; save_all()
    G.result = { special = true, kind = B.special, idx = B.special_idx, lv = B.lv }
    B.lv = 0
    set_page("result"); beep(880, 90)
    return
  end
  -- 限制技能模式: 统一判定 (无尽模式仍走正常结算)
  if B.restricted and not G.mode_endless then
    local full, correct = true, true
    for k = 1, 81 do
      if B.val[k] == 0 then full = false end
      if B.val[k] ~= B.sol[k] then correct = false end
    end
    if not full then toast("棋盘尚未完成。", 1500); G.dirty = true; return end
    if not correct then toast("答案不正确，请自行检查。", 1800); G.dirty = true; return end
    -- 填满且正确: 继续走下方普通结算
  end
  local score = gain(B.err)
  if G.mode_endless then
    G.endless.n = G.endless.n + 1
    G.endless.score = G.endless.score + score
    if G.endless.n > (G.endless_best or 0) then G.endless_best = G.endless.n end
    if G.endless.score > (G.endless_best_score or 0) then G.endless_best_score = G.endless.score end
    -- 连续完美奖励 (里程碑不重复领取)
    if score == 3 then
      G.endless.perfect_streak = (G.endless.perfect_streak or 0) + 1
      if G.endless.perfect_streak == 3 and not G.endless.bonus3 then
        G.endless.bonus3 = true; G.endless.score = G.endless.score + 2; G.endless_last_bonus = "连续完美 +2 分"
      elseif G.endless.perfect_streak == 5 and not G.endless.bonus5 then
        G.endless.bonus5 = true; G.endless.score = G.endless.score + 3; G.endless_last_bonus = "连续完美 +3 分"
      end
    else
      G.endless.perfect_streak = 0
    end
    -- 连续 3 道 0 分 ⇒ 本轮结束
    if score == 0 then G.endless.zero_streak = (G.endless.zero_streak or 0) + 1
    else G.endless.zero_streak = 0 end
    -- 最近题目去重记录 (最多 10)
    local rec = G.endless.recent or {}
    rec[#rec+1] = B.lv
    while #rec > 10 do table.remove(rec, 1) end
    G.endless.recent = rec
    if G.endless.zero_streak >= 3 then G.endless.over = true end
    G.save_dirty = true; save_all()
    B.lv = 0
    if G.endless.over then
      G.result = { endless=true, n=G.endless.n, total=G.endless.score, over=true, err=B.err, score=score }
      set_page("result"); beep(880, 90); return
    end
    local msg = G.endless_last_bonus or ("本层 " .. score .. " 分")
    G.endless_last_bonus = nil
    toast(msg .. "  继续下一题", 1100)
    start_endless()                    -- 自动进入下一题 (连续游玩)
    return
  end
  local award = score - G.rec[lv].paid
  if award < 0 then award = 0 end
  G.points = G.points + award
  G.claimed = G.claimed + award
  G.rec[lv].paid = math.max(G.rec[lv].paid, score)
  G.rec[lv].best = math.max(G.rec[lv].best, score)
  G.rec[lv].done = 1
  G.active_lv = 0
  B.lv = 0
  G.result = { lv=lv, err=B.err, score=score, award=award }
  G.save_dirty = true
  save_all()
  set_page("result")
  beep(880, 90)
end

-- 该格是否已"确定"(不可再改): 原题, 或玩家已经填**对**的
local function cell_fixed(i)
  if B.given[i] ~= 0 then return true end
  return B.who[i] == 2 and B.val[i] ~= 0 and B.val[i] == B.sol[i]
end

local function put_digit(i, d)
  if B.restricted then
    -- 受限模式: 取消"填错即拒绝/扣分/震动"; 允许向任意非给定空格写 1-9
    if B.given[i] ~= 0 then toast("这格已给定, 不能改"); return end
    if B.who[i] == 2 and B.val[i] == d then return end   -- 同格同值不重复
    B.val[i], B.who[i], B.notes[i] = d, 2, 0
    B.wrong[i], B.lastbad[i] = false, 0                   -- 永不标记错格
    beep(660, 35)
    recount()
    local full = true
    for k = 1, 81 do if B.val[k] == 0 then full = false; break end end
    if full then finish_level() end                       -- 填满即统一判定
    G.save_dirty = true; G.dirty = true
    return
  end
  if cell_fixed(i) then toast("这格已确定, 不能改"); return end
  if B.val[i] == d and B.who[i] == 2 then return end   -- 同一格重复点同一错误值不重复计错
  -- ★ 2026-11-08 linit: 错误的数字**直接拒绝写入**, 只弹一次提示。
  --   每错一次本关少 1 分(3 分 → 2 → 1 → 0), 一关最多扣 3 分。
  if (d ~= B.sol[i]) or conflict(i, d) then
    B.err = B.err + 1
    beep(220, 70); buzz()
    if B.err <= 3 then
      toast("填错了  本关 -" .. B.err .. " 分", 800)
    else
      toast("填错了  本关已扣满 3 分", 900)
    end
    G.save_dirty = true
    G.dirty = true
    return
  end
  B.val[i], B.who[i], B.notes[i] = d, 2, 0
  B.wrong[i], B.lastbad[i] = false, 0
  beep(660, 35)
  recount()
  auto_update_notes()
  -- 自动填充的级联过程中跳过重活(技巧扫描/完成判定), 由 auto_fill_chain 收尾时统一做一次,
  -- 否则一次落子可能连跑几十轮 refresh_tip, 手感会明显变迟钝。
  if not G.filling then
    refresh_tip()
    check_complete()
    G.fill_pending = true       -- 交给 poll 消费(避免与外部调用重入)
  end
  G.save_dirty = true
  G.dirty = true
end

-- ====================== 自动填充技能 (2026-11-08 新增) ======================
-- 等级与判据 (linit 指定, 由易到难):
--   Lv1 九宫内"最后空格"(某宫只剩一格)        Lv2 +整行    Lv3 +整列
--   Lv4 九宫内"候选唯一"(裸单)               Lv5 +整行    Lv6 +整列
-- 每次落子后自动跑一轮, 并且**级联**: 填出来的新数会解锁下一层唯一解, 一直填到没有进展。
-- ⚠ 只填与 B.sol 一致的数字 —— 玩家自己填错的格子绝不替他"改正"(那是作弊, 也会破坏计时/错误统计)。
-- ★ 2026-11-22: 掩码只有 9 位(0..511), 查表替代逐位循环。
--   实测基点: scan_techniques 里 bitcnt 被调用上万次 (裸三数组是 27 单元 × O(空³)),
--   这是技巧扫描最热的指令段 —— 每次落子都会跑一遍, 直接决定落子延迟。
local BITCNT = {}
do
  for m = 0, 511 do
    local x, n = m, 0
    while x ~= 0 do n = n + (x & 1); x = x >> 1 end
    BITCNT[m] = n
  end
end
local function bitcnt(x) return BITCNT[x] or 0 end

local function bitlist(m)
  local t = {}
  for d = 1, 9 do if (m & (1 << (d-1))) ~= 0 then t[#t+1] = d end end
  return t
end

local function unit_kind(ui)
  if ui <= 9  then return 1 end     -- 行
  if ui <= 18 then return 2 end     -- 列
  return 3                          -- 宫
end

local function find_fill_target(lv)
  -- ① 唯一空: 单元里只剩一个空格
  for ui, u in ipairs(UNITS) do
    local k = unit_kind(ui)
    local allow = (k == 3 and lv >= 1) or (k == 1 and lv >= 2) or (k == 2 and lv >= 3)
    if allow then
      local empty, cnt, used = nil, 0, {}
      for _, i in ipairs(u) do
        local v = B.val[i]
        if v ~= 0 then used[v] = true else cnt = cnt + 1; empty = i end
      end
      if cnt == 1 and empty then
        for d = 1, 9 do
          if not used[d] then return empty, d end
        end
      end
    end
  end
  -- ② 候选唯一(裸单): 某空格的候选只剩一个数字
  local cd = cand_map()
  for ui, u in ipairs(UNITS) do
    local k = unit_kind(ui)
    local allow = (k == 3 and lv >= 4) or (k == 1 and lv >= 5) or (k == 2 and lv >= 6)
    if allow then
      for _, i in ipairs(u) do
        if B.val[i] == 0 then
          local m = cd[i]
          if m ~= 0 and bitcnt(m) == 1 then
            local d = bitlist(m)[1]
            if d then return i, d end
          end
        end
      end
    end
  end
  return nil
end

function auto_fill_chain()
  if B.restricted then return 0 end  -- 受限模式: 禁用自动填充技能
  local lv = G.skill.fill or 0
  if lv <= 0 or G.filling then return 0 end
  G.filling = true
  local total = 0
  for _ = 1, 81 do                       -- 最多填满整盘, 防御死循环
    local i, d = find_fill_target(lv)
    if not i or not d then break end
    if B.val[i] ~= 0 or d ~= B.sol[i] then break end   -- 双保险: 只填正确答案
    put_digit(i, d)
    total = total + 1
  end
  G.filling = false
  if total > 0 then
    refresh_tip()
    check_complete()
    G.dirty = true
  end
  return total
end

local function erase_cell(i)
  if B.given[i] ~= 0 then toast("这格已给定, 不能擦"); return end
  if B.restricted then
    -- 受限模式: 允许擦除玩家填的格 (含错填) 与手动笔记, 但不动给定格
    if B.val[i] ~= 0 then
      B.val[i], B.who[i], B.wrong[i], B.lastbad[i] = 0, 0, false, 0; beep(440, 30)
    elseif (B.notes[i] or 0) ~= 0 then
      B.notes[i] = 0; beep(440, 30)
    else return end
    recount(); G.save_dirty = true; G.dirty = true
    return
  end
  -- ★ 2026-11-08 linit: 玩家自己填的格子**一律可擦**(原来连填对的都不给擦 ⇒ 想改主意
  --   或想重置错填都没办法, 左侧卡片数量也永远回不去)。原题给定格仍然不许动。
  if B.val[i] ~= 0 and B.who[i] == 2 then
    B.val[i], B.who[i], B.wrong[i], B.lastbad[i] = 0, 0, false, 0
    beep(440, 30)
  elseif (B.notes[i] or 0) ~= 0 then
    B.notes[i] = 0
    beep(440, 30)
  else
    return
  end
  recount()
  auto_update_notes()
  refresh_tip()
  G.save_dirty = true
  G.dirty = true
end

local function toggle_note(i, d)
  if B.val[i] ~= 0 then toast("此格已有数字"); return end
  B.notes[i] = (B.notes[i] or 0) ~ (1 << (d-1))
  B.manual[i] = true
  refresh_tip()
  G.save_dirty = true
  G.dirty = true
  beep(520, 25)
end

local function auto_notes()
  if B.restricted then toast("受限模式已禁用技能", 900); return end
  local n = 0
  local cd = cand_map()
  for i = 1, 81 do
    if B.val[i] == 0 then
      B.notes[i] = cd[i]
      B.manual[i] = false
      n = n + 1
    end
  end
  G.save_dirty = true; G.dirty = true
  toast("已自动填充 " .. n .. " 格候选")
end

local function clean_notes()
  local n = 0
  local cd = cand_map()
  for i = 1, 81 do
    if B.val[i] == 0 and (B.notes[i] or 0) ~= 0 then
      local old = B.notes[i]
      B.notes[i] = old & cd[i]
      if B.notes[i] ~= old then n = n + 1 end
    end
  end
  G.save_dirty = true; G.dirty = true
  toast("已清理 " .. n .. " 格非法候选")
end

local function clear_notes()
  for i = 1, 81 do B.notes[i] = 0; B.manual[i] = false end
  G.save_dirty = true; G.dirty = true
  toast("已清除全部候选")
end

-- ------------------------------ 技巧扫描 --------------------------------
-- 基于"当前棋盘真实合法候选"扫描, 不使用题解、不修改玩家笔记、不自动填数。
-- 返回按等级升序的结果列表; 每条 {lv,name,desc,cells,focus,elim}。
-- focus[i] / elim[i] = 数字掩码, 用于格内高亮 / 删除标记。

local function cell_desc(i)
  return "第" .. ((i-1)//9 + 1) .. "行" .. ((i-1)%9 + 1) .. "列"
end

function scan_techniques()
  local out = {}
  if B.restricted then return out end  -- 受限模式: 禁用技巧扫描
  local maxlv = G.skill.tip
  if maxlv <= 0 then return out end
  local c = cand_map()            -- 共享只读缓存 (见 cand_map 说明)
  local function add(lv, name, desc, cells, focus, elim)
    if lv <= maxlv then
      out[#out+1] = { lv=lv, name=name, desc=desc, cells=cells,
                      focus=focus or {}, elim=elim or {} }
    end
  end

  -- L1 裸单
  for i = 1, 81 do
    if B.val[i] == 0 and bitcnt(c[i]) == 1 then
      local d = bitlist(c[i])[1]
      add(1, "裸单", "此处只能填" .. d,
          {i}, {[i]=1 << (d-1)}, {})
    end
  end
  -- L1 隐性单
  for ui, u in ipairs(UNITS) do
    for d = 1, 9 do
      local mask = 1 << (d-1)
      local spots = {}
      for _, i in ipairs(u) do
        if B.val[i] == 0 and (c[i] & mask) ~= 0 then spots[#spots+1] = i end
      end
      if #spots == 1 then
        local un = ui <= 9 and "行" or (ui <= 18 and "列" or "宫")
        add(1, "隐性单", "本" .. un .. "只有此格填" .. d,
            spots, {[spots[1]]=mask}, {})
      end
    end
  end
  if maxlv >= 2 then
    -- L2 裸数对
    for _, u in ipairs(UNITS) do
      local em = {}
      for _, i in ipairs(u) do if B.val[i] == 0 then em[#em+1] = i end end
      for a = 1, #em do
        if bitcnt(c[em[a]]) == 2 then
          for b = a+1, #em do
            if c[em[b]] == c[em[a]] then
              local elim, changed = {}, false
              for _, i in ipairs(em) do
                if i ~= em[a] and i ~= em[b] and (c[i] & c[em[a]]) ~= 0 then
                  elim[i] = c[i] & c[em[a]]; changed = true
                end
              end
              if changed then
                local ds = bitlist(c[em[a]])
                add(2, "裸数对", "两格只填" .. ds[1] .. "和" .. ds[2] .. ", 可删其余",
                    {em[a], em[b]}, {[em[a]]=c[em[a]], [em[b]]=c[em[b]]}, elim)
              end
            end
          end
        end
      end
    end
    -- L2 隐性数对
    for _, u in ipairs(UNITS) do
      local em = {}
      for _, i in ipairs(u) do if B.val[i] == 0 then em[#em+1] = i end end
      local pos = {}
      for d = 1, 9 do
        pos[d] = {}
        for _, i in ipairs(em) do
          if (c[i] & (1 << (d-1))) ~= 0 then pos[d][#pos[d]+1] = i end
        end
      end
      for d1 = 1, 9 do
        if #pos[d1] == 2 then
          for d2 = d1+1, 9 do
            if #pos[d2] == 2 and pos[d1][1] == pos[d2][1]
               and pos[d1][2] == pos[d2][2] then
              local keep = (1 << (d1-1)) | (1 << (d2-1))
              local changed, focus = false, {}
              for _, i in ipairs(pos[d1]) do
                if (c[i] & ~keep) ~= 0 then changed = true end
                focus[i] = keep
              end
              if changed then
                add(2, "隐性数对", d1 .. "和" .. d2 .. "只在这两格",
                    pos[d1], focus, {})
              end
            end
          end
        end
      end
    end
  end
  if maxlv >= 3 then
    -- L3 宫区块排除 (pointing)
    for bi = 19, 27 do
      local u = UNITS[bi]
      for d = 1, 9 do
        local mask = 1 << (d-1)
        local spots = {}
        for _, i in ipairs(u) do
          if B.val[i] == 0 and (c[i] & mask) ~= 0 then spots[#spots+1] = i end
        end
        if #spots >= 2 then
          local rows, cols = {}, {}
          for _, i in ipairs(spots) do
            rows[(i-1)//9] = true; cols[(i-1)%9] = true
          end
          local rn, cn = 0, 0
          for _ in pairs(rows) do rn = rn + 1 end
          for _ in pairs(cols) do cn = cn + 1 end
          local lines = {}
          if rn == 1 then for r in pairs(rows) do lines[#lines+1] = UNITS[r+1] end end
          if cn == 1 then for cc in pairs(cols) do lines[#lines+1] = UNITS[9+cc+1] end end
          local boxset = {}
          for _, i in ipairs(u) do boxset[i] = true end
          for _, line in ipairs(lines) do
            local elim, changed = {}, false
            for _, i in ipairs(line) do
              if not boxset[i] and B.val[i] == 0 and (c[i] & mask) ~= 0 then
                elim[i] = mask; changed = true
              end
            end
            if changed then
              add(3, "宫区块排除", "本宫" .. d .. "只在一行/列",
                  spots, {[spots[1]]=mask}, elim)
            end
          end
        end
      end
    end
    -- L3 宫行排除 (claiming)
    for ui = 1, 18 do
      local u = UNITS[ui]
      for d = 1, 9 do
        local mask = 1 << (d-1)
        local spots, boxes = {}, {}
        for _, i in ipairs(u) do
          if B.val[i] == 0 and (c[i] & mask) ~= 0 then
            spots[#spots+1] = i
            boxes[BOX_ID[i]] = true
          end
        end
        local nb = 0
        for _ in pairs(boxes) do nb = nb + 1 end
        if #spots >= 2 and nb == 1 then
          local bi = next(boxes)
          local box = UNITS[18 + bi]
          local inset = {}
          for _, i in ipairs(u) do inset[i] = true end
          local elim, changed = {}, false
          for _, i in ipairs(box) do
            if not inset[i] and B.val[i] == 0 and (c[i] & mask) ~= 0 then
              elim[i] = mask; changed = true
            end
          end
          if changed then
            add(3, "宫行排除", "本行" .. d .. "只在此宫",
                spots, {[spots[1]]=mask}, elim)
          end
        end
      end
    end
    -- L3 裸三数组
    for _, u in ipairs(UNITS) do
      local em = {}
      for _, i in ipairs(u) do
        if B.val[i] == 0 and bitcnt(c[i]) >= 2 and bitcnt(c[i]) <= 3 then em[#em+1] = i end
      end
      for a = 1, #em do for b = a+1, #em do for e = b+1, #em do
        local tri = { em[a], em[b], em[e] }
        local union = c[tri[1]] | c[tri[2]] | c[tri[3]]
        if bitcnt(union) == 3 then
          local inset, elim, changed = {}, {}, false
          for _, i in ipairs(tri) do inset[i] = true end
          for _, i in ipairs(u) do
            if B.val[i] == 0 and not inset[i] and (c[i] & union) ~= 0 then
              elim[i] = c[i] & union; changed = true
            end
          end
          if changed then
            local ds = bitlist(union)
            add(3, "裸三数组", "三格只填" .. ds[1] .. ds[2] .. ds[3],
                tri, {[tri[1]]=union, [tri[2]]=union, [tri[3]]=union}, elim)
          end
        end
      end end end
    end
    -- L3 隐性三数组
    for _, u in ipairs(UNITS) do
      local em = {}
      for _, i in ipairs(u) do if B.val[i] == 0 then em[#em+1] = i end end
      local pos = {}
      for d = 1, 9 do
        pos[d] = {}
        for _, i in ipairs(em) do
          if (c[i] & (1 << (d-1))) ~= 0 then pos[d][#pos[d]+1] = i end
        end
      end
      local ds = {}
      for d = 1, 9 do if #pos[d] >= 2 and #pos[d] <= 3 then ds[#ds+1] = d end end
      for a = 1, #ds do for b = a+1, #ds do for e = b+1, #ds do
        local set = {}
        for _, d in ipairs({ds[a], ds[b], ds[e]}) do
          for _, i in ipairs(pos[d]) do set[i] = true end
        end
        local cells, n = {}, 0
        for i in pairs(set) do cells[#cells+1] = i; n = n + 1 end
        if n == 3 then
          local keep, focus, changed = 0, {}, false
          for _, d in ipairs({ds[a], ds[b], ds[e]}) do keep = keep | (1 << (d-1)) end
          for _, i in ipairs(cells) do
            focus[i] = keep
            if (c[i] & ~keep) ~= 0 then changed = true end
          end
          if changed then
            add(3, "隐性三数组", "三数只在这三格", cells, focus, {})
          end
        end
      end end end
    end
  end
  if maxlv >= 4 then
    -- L4 X-Wing (行版 + 列版)
    for d = 1, 9 do
      local mask = 1 << (d-1)
      for base = 1, 2 do
        local pat = {}
        for k = 0, 8 do
          local line = UNITS[(base == 1 and k or 9+k) + 1]
          local spots = {}
          for _, i in ipairs(line) do
            if B.val[i] == 0 and (c[i] & mask) ~= 0 then
              spots[#spots+1] = (base == 1) and ((i-1)%9) or ((i-1)//9)
            end
          end
          if #spots == 2 then
            local key = spots[1] .. "," .. spots[2]
            pat[key] = pat[key] or {}
            pat[key][#pat[key]+1] = { k=k, spots=spots }
          end
        end
        for _, group in pairs(pat) do
          if #group >= 2 then
            for a = 1, #group do for b = a+1, #group do
              local g1, g2 = group[a], group[b]
              local inset = {}
              for _, i in ipairs(UNITS[(base == 1 and g1.k or 9+g1.k) + 1]) do inset[i] = true end
              for _, i in ipairs(UNITS[(base == 1 and g2.k or 9+g2.k) + 1]) do inset[i] = true end
              local elim, changed = {}, false
              for _, col in ipairs(g1.spots) do
                local cross = UNITS[(base == 1 and 9+col or col) + 1]
                for _, i in ipairs(cross) do
                  if not inset[i] and B.val[i] == 0 and (c[i] & mask) ~= 0 then
                    elim[i] = mask; changed = true
                  end
                end
              end
              if changed then
                local cells = {}
                for _, col in ipairs(g1.spots) do
                  cells[#cells+1] = (base == 1) and (g1.k*9+col+1) or (col*9+g1.k+1)
                  cells[#cells+1] = (base == 1) and (g2.k*9+col+1) or (col*9+g2.k+1)
                end
                local focus = {}
                for _, i in ipairs(cells) do focus[i] = mask end
                add(4, "X-Wing", d .. "在两" .. (base == 1 and "行" or "列")
                    .. "只占同两" .. (base == 1 and "列" or "行"),
                    cells, focus, elim)
              end
            end end
          end
        end
      end
    end
  end
  return out
end

-- 自动技巧: 技能 Lv>0 就生效, 不需要手动开启。取扫描到的第一条结果做高亮。
function refresh_tip()
  if B.restricted then G.hs = nil; G.tip = nil; return end  -- 受限模式: 关闭高亮/提示
  G.hs = hidden_single_map()
  if G.skill.tip <= 0 or has_wrong() then G.tip = nil; return end
  -- ★ 2026-11-22: 只为取"等级最高的一条", 一次遍历即可。
  --   原来 table.sort 会把整张结果表(可能上百条)按闭包比较排一遍, 纯属浪费;
  --   同一等级取先扫到的那条, 与 sort 的不稳定顺序等价, 但不会每次抖动。
  local list = scan_techniques()
  local best
  for k = 1, #list do
    local t = list[k]
    if not best or (t.lv or 0) > (best.lv or 0) then best = t end
  end
  G.tip = best
end

