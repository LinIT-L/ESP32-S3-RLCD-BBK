local function load_game()
  local body = unpack_save(app.nvs.get_str(K_GAME), "G")
  if not body or body == "none" then return false end
  local f = split(body, "|")
  if f[1] ~= "G1" or #f < 5 or not PUZZLE_DATA[1] then return false end
  local lv = tonumber(f[2]) or 0
  if lv < 1 or lv > 60 or not PUZZLE_DATA[lv] then return false end
  local bd, ns = f[4], f[5]
  if #bd ~= 81 then return false end
  start_level(lv, true)
  B.err = clamp(tonumber(f[3]) or 0, 0, 999)
  for i = 1, 81 do
    local ch = bd:sub(i, i)
    local b = ch:byte()
    if ch == "0" then
      B.val[i], B.who[i], B.wrong[i] = 0, 0, false
    elseif ch >= "1" and ch <= "9" then
      local d = b - 48
      if B.given[i] ~= d then return false end
      B.val[i], B.who[i], B.wrong[i] = d, 1, false
    elseif b >= 65 and b <= 73 then
      if B.given[i] ~= 0 then return false end
      B.val[i], B.who[i], B.wrong[i] = b - 64, 2, false
    elseif b >= 97 and b <= 105 then
      if B.given[i] ~= 0 then return false end
      B.val[i], B.who[i], B.wrong[i] = b - 96, 2, true
    else
      return false
    end
  end
  B.notes = {}
  for i = 1, 81 do B.notes[i] = 0 end
  if #ns % 5 == 0 then
    for k = 1, #ns, 5 do
      local idx = tonumber(ns:sub(k, k+1))
      local m = tonumber(ns:sub(k+2, k+4), 16)
      if idx and m and idx >= 1 and idx <= 81 then B.notes[idx] = m % 512 end
    end
  end
  recount()
  return true
end

-- -------------------------------- 局面 ----------------------------------
function recount()
  B.gen = (B.gen or 0) + 1        -- 棋盘版本号: 定位标记缓存用
  for d = 1, 9 do B.cnt[d] = 0 end
  for i = 1, 81 do
    local v = B.val[i]
    if v >= 1 and v <= 9 then B.cnt[v] = B.cnt[v] + 1 end
  end
  -- ★ 2026-11-08 linit: 当前选中的数字一旦用尽(棋盘上 9 个都在了), 必须**立即**清掉待填状态,
  --   不能留一个已经隐藏的卡片还挂着选中 —— 否则再点空格会继续用这个用完的数字。
  if B.pend > 0 and (B.cnt[B.pend] or 0) >= 9 then B.pend = 0 end
end

