-- ★ 2026-11-08: 行列宫关联底色改成 1:1 菱形棋盘格 (原来 6% 稀疏点阵, 太淡看不见)。
-- 位图 5 字节/行(40 位) x 34 行, (x+y)%2==0 处为黑 —— 密度 50%, 45 度菱形网格。
-- 用 app.bmp 一次画整格 (81 格/帧), 比逐点 app.px 快 200 倍。
local CHESS_HEX = "aaaaaaaaaa5555555555aaaaaaaaaa5555555555aaaaaaaaaa5555555555aaaaaaaaaa5555555555aaaaaaaaaa5555555555aaaaaaaaaa5555555555aaaaaaaaaa5555555555aaaaaaaaaa5555555555aaaaaaaaaa5555555555aaaaaaaaaa5555555555aaaaaaaaaa5555555555aaaaaaaaaa5555555555aaaaaaaaaa5555555555aaaaaaaaaa5555555555aaaaaaaaaa5555555555aaaaaaaaaa5555555555aaaaaaaaaa5555555555"

local function dither_cell(cx, cy, w, h, white)
  if white then
    -- 深灰(黑底白点): 只给笔记反色用, 保持稀疏点阵
    local c = WH
    for y = 1, h - 2, 4 do
      local xs = (((y - 1) // 4) % 2 == 0) and 1 or 3
      for x = xs, w - 2, 4 do app.px(cx + x, cy + y, c) end
    end
  else
    app.bmp(cx, cy, w, h, CHESS_HEX)      -- 白底 + 50% 黑点
  end
end

-- 相同数字格: 纯反色 + 白字 (与"选中格"同语义: 都是被选中)
-- ★ 2026-11-08 linit: 原来填 cx+1..cx+w-2 / cy+1..cy+h-2, 右边缘和下边缘各差 1px
