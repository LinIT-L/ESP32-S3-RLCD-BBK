local function conflict(i, d)
  for _, j in ipairs(PEER[i]) do
    if B.val[j] == d then return true end
  end
  return false
end

function cand_of(i)
  if B.val[i] ~= 0 then return 0 end
  local m = FULL
  for _, j in ipairs(PEER[i]) do
    local v = B.val[j]
    if v >= 1 and v <= 9 then m = m & ~(1 << (v-1)) end
  end
  return m
end

-- ★ 2026-11-22: 全盘候选缓存。一次 O(81×20) 替代各处重复现算 ——
--   draw_board / scan_techniques / hidden_single_map / loc_marks / find_fill_target
--   原先各自把 81 格算一遍, 同一帧内要算三到四遍。
--   键用 B.gen (recount 在每次落子/擦除时 ++), 盘面没变就复用。
--   ⚠ 返回的是共享表: 调用方**只许读**; 若要写候选请自行建表。
local s_cand, s_cand_gen = {}, -1
local function cand_map()
  if s_cand_gen == B.gen then return s_cand end
  for i = 1, 81 do s_cand[i] = cand_of(i) end
  s_cand_gen = B.gen
  return s_cand
end

-- 自动笔记: 升级即自动生效 (不覆盖玩家手动改过的格)
function auto_fill_notes()
  if B.restricted then return end   -- 受限模式: 禁止后台自动生成候选
  if G.skill.auto < 1 then return end
  local cd = cand_map()             -- 一次算全盘 (候选只依赖 B.val, 此函数只改 notes)
  for i = 1, 81 do
    if B.val[i] == 0 and not B.manual[i] then B.notes[i] = cd[i] end
  end
end

function auto_update_notes()
  if B.restricted then return end   -- 受限模式: 不自动刷新候选
  if G.skill.auto < 2 then return end
  local cd = cand_map()
  -- Lv2: 删掉与当前棋盘冲突的候选 (冲突候选一定是错的, 删了不算覆盖玩家意图)
  for i = 1, 81 do
    if B.val[i] == 0 and (B.notes[i] or 0) ~= 0 then
      B.notes[i] = B.notes[i] & cd[i]
    end
  end
  -- Lv3: 候选被清空的空格重新补全
  if G.skill.auto >= 3 then
    for i = 1, 81 do
      if B.val[i] == 0 and (B.notes[i] or 0) == 0 then B.notes[i] = cd[i] end
    end
  end
end

-- Lv4: 隐性单 (某单元里某数字只剩一个可放位置) 用反白标出
-- 只标"选中格所在的行/列/宫", 否则全盘反白会把棋盘糊成一片
-- ★ 2026-11-22: 加 (棋盘版本, 选中格) 双键缓存 —— 它每次 refresh_tip 都被调用,
--   而落子/擦除会连带调用 refresh_tip, 原实现每次都要重算 3 单元 × 27 格候选。
local EMPTY_MAP = {}
local s_hs_gen, s_hs_sel, s_hs_t = -1, -1, EMPTY_MAP
function hidden_single_map()
  if G.skill.auto < 4 or B.sel < 1 or B.sel > 81 then return EMPTY_MAP end
  if s_hs_gen == B.gen and s_hs_sel == B.sel then return s_hs_t end
  local t = {}
  local sel = B.sel
  local r, c, bx = (sel-1)//9, (sel-1)%9, BOX_ID[sel]
  local units = { UNITS[r+1], UNITS[9+c+1], UNITS[18+bx] }
  local cd = cand_map()            -- 共享只读缓存
  for _, u in ipairs(units) do
    for d = 1, 9 do
      local mask = 1 << (d-1)
      local spot, cnt = nil, 0
      for _, i in ipairs(u) do
        if B.val[i] == 0 and (cd[i] & mask) ~= 0 then cnt = cnt + 1; spot = i end
      end
      if cnt == 1 and spot then t[spot] = mask end
    end
  end
  s_hs_gen, s_hs_sel, s_hs_t = B.gen, sel, t
  return t
end

