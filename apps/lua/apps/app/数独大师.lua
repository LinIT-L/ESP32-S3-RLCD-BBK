-- 16px 混合字自动折行: 汉字 16 / ASCII 8, 右栏提示用
local function mix_wrap(x, y, str, maxw, maxlines, lh)
  local i, n = 1, #str
  local line, cx, ly = 1, 0, y
  while i <= n and line <= maxlines do
    local b = str:byte(i)
    local w, len
    if b < 0x80 then w, len = 8, 1
    elseif b >= 0xF0 then w, len = 16, 4
    elseif b >= 0xE0 then w, len = 16, 3
    else w, len = 16, 2 end
    if cx + w > maxw then
      line, cx = line + 1, 0
      if line > maxlines then break end
      ly = ly + lh
    end
    app.mix(x + cx, ly, str:sub(i, i+len-1))
    cx = cx + w
    i = i + len
  end
end

-- 12px 小字自动折行 (每行 maxw 内, 最多 maxlines 行)
local function smix_wrap(x, y, str, maxw, maxlines, lh)
  local i, n = 1, #str
  local line, cx = 1, 0
  local ly = y
  while i <= n and line <= maxlines do
    local b = str:byte(i)
    local w, len
    if b < 0x80 then w, len = 8, 1
    elseif b >= 0xF0 then w, len = 12, 4
    elseif b >= 0xE0 then w, len = 12, 3
    else w, len = 12, 2 end
    if cx + w > maxw then
      line, cx = line + 1, 0
      if line > maxlines then break end
      ly = ly + lh
    end
    smix(x + cx, ly, str:sub(i, i+len-1))
    cx = cx + w
    i = i + len
  end
end

