def read_pool(txt=None):
    """读 60 题原始池。优先 tools/sudoku_pool60.json（首次运行从 Lua 里抽取并固化），
    保证本脚本可重复运行、重跑结果稳定。"""
    import json
    if os.path.exists(POOL_JSON):
        with open(POOL_JSON, encoding="utf-8") as f:
            return json.load(f)
    txt = txt if txt is not None else open(APP, encoding="utf-8").read()
    b = "PUZZLES BEGIN"
    e = "PUZZLES END"
    i, j = txt.find(b), txt.find(e)
    if i < 0 or j < 0 or j < i:
        return []
    seg = txt[i:j]
    out = []
    for m in re.finditer(r'\{p="([0-9]{81})", s="([0-9]{81})"', seg):
        out.append({"p": m.group(1), "s": m.group(2)})
    if len(out) == 60:
        with open(POOL_JSON, "w", encoding="utf-8") as f:
            json.dump(out, f)
    return out


# ---------------------------------------------------------------- 组织 60 关
def reorganise(rng):
    """第 1 章重建；第 2..6 章按实测难度重排旧题。"""
    old = read_pool()
    if len(old) != 60:
        print("读现有题库失败: %d 题" % len(old), file=sys.stderr)
        return None
    pool = []
    for n, it in enumerate(old, 1):
        p = parse(it["p"])
        a = analyse(p, parse(it["s"]))
        if not a["solvable"]:
            print("旧题 %d 无法纯逻辑解，剔除" % n, file=sys.stderr)
            continue
        pool.append({"p": it["p"], "s": it["s"], "old": n, "a": a})

    # 旧第 1 章(10 题) → 新第 2 章(基础篇, 唯一候选, 空格多一档)
    # 旧第 2 章(10 题) → 新第 3 章(进阶篇, 隐性唯一)
    # 旧第 3/4/5 章(30 题) → 新第 4/5 章(技巧篇/挑战篇) 取难度最低 10 / 最高 10
    # 旧第 6 章(10 题) → 新第 6 章(高手篇, X-Wing)
    ch_old = {c: [x for x in pool if (x["old"] - 1) // 10 == c] for c in range(6)}
    for c in range(6):
        if len(ch_old[c]) != 10:
            print("旧第 %d 章不足 10 题(%d)" % (c + 1, len(ch_old[c])), file=sys.stderr)
            return None

    def key(x):
        return (x["a"]["lv"], x["a"]["steps"], x["a"]["holes"])

    ch2 = sorted(ch_old[0], key=key)
    ch3 = sorted(ch_old[1], key=key)
    mid = sorted(ch_old[2] + ch_old[3] + ch_old[4], key=key)
    ch4 = mid[:10]
    ch5 = mid[10:20]
    ch6 = sorted(ch_old[5], key=key)

    # 第 1 章: 定向构造
    ch1 = []
    used_p = {x["p"] for x in pool}
    for k, spec in enumerate(TEACH_SPEC, 1):
        got = None
        for _ in range(6):
            got = build_teaching(rng, spec)
            if got and got[0] not in used_p:
                break
            got = None
        if not got:
            print("第 1 章第 %d 关构造失败 %s" % (k, spec), file=sys.stderr)
            return None
        used_p.add(got[0])
        ch1.append({"p": got[0], "s": got[1], "a": got[2], "new": True})

    chapters = [ch1, ch2, ch3, ch4, ch5, ch6]
    out = []
    for c, items in enumerate(chapters):
        for x in items:
            out.append({"p": x["p"], "s": x["s"], "lv": x["a"]["lv"],
                        "holes": x["a"]["holes"], "tech": x["a"]["tech"],
                        "steps": x["a"]["steps"], "ch": c})
    return out, pool, mid[10:]


# --------------------------------------------------------------- 校验
def verify(levels, endgames, classics, verbose=True):
    errs = []
    if len(levels) != 60:
        errs.append("主线题数 %d != 60" % len(levels))
    if len(endgames) != 6:
        errs.append("残局数 %d != 6" % len(endgames))
    if len(classics) != 6:
        errs.append("名题数 %d != 6" % len(classics))

    seen_p, seen_s, seen_sig = set(), set(), set()
    for n, it in enumerate(levels, 1):
        p, s = parse(it["p"]), parse(it["s"])
        if not sg.valid_complete(s):
            errs.append("第%d关 解答不是合法完整解" % n)
        if any(p[i] and p[i] != s[i] for i in range(81)):
            errs.append("第%d关 给定与解答冲突" % n)
        if sg.count_solutions(p, 2) != 1:
            errs.append("第%d关 不是唯一解" % n)
        a = analyse(p, s)
        if not a["solvable"]:
            errs.append("第%d关 需要猜测" % n)
        if a["lv"] != it["lv"] or a["holes"] != it["holes"]:
            errs.append("第%d关 记录(lv=%d,holes=%d) 实测(lv=%d,holes=%d)"
                        % (n, it["lv"], it["holes"], a["lv"], a["holes"]))
        ch = (n - 1) // 10
        if ch == 0:
            if a["lv"] != 1 or a["first_naked"] == 0:
                errs.append("第%d关 启蒙题不满足「首步显性唯一」" % n)
        if ch >= 1 and it["lv"] < levels[ch * 10]["lv"] - 0:
            pass
        if it["p"] in seen_p:
            errs.append("第%d关 题目重复" % n)
        sig = tuple(i for i, v in enumerate(p) if v == 0)
        if sig in seen_sig:
            errs.append("第%d关 空格模式重复" % n)
        if it["s"] in seen_s:
            errs.append("第%d关 解答重复" % n)
        seen_p.add(it["p"]); seen_s.add(it["s"]); seen_sig.add(sig)

    # 章节内难度不许倒挂（同章按 lv 升序、再按步数升序）
    for c in range(6):
        seg = levels[c * 10:(c + 1) * 10]
        keys = [(x["lv"], x["steps"]) for x in seg]
        if keys != sorted(keys):
            errs.append("第%d章 难度倒挂 %s" % (c + 1, keys))

    for n, it in enumerate(endgames, 1):
        p, s = parse(it["p"]), parse(it["s"])
        if sg.count_solutions(p, 2) != 1:
            errs.append("残局%d 不是唯一解" % n)
        a = analyse(p, s)
        if not a["solvable"] or a["lv"] != 1:
            errs.append("残局%d 需要技巧或猜测 (lv=%d)" % (n, a["lv"]))
        if a["first_naked"] != a["holes"]:
            errs.append("残局%d 并非每个空格都能直接看出" % n)
        if not (4 <= a["holes"] <= 8):
            errs.append("残局%d 空格数 %d 不在 4..8" % (n, a["holes"]))

    for n, it in enumerate(classics, 1):
        p, s = parse(it["p"]), parse(it["s"])
        if sg.count_solutions(p, 2) != 1:
            errs.append("名题%d 不是唯一解" % n)
        a = analyse(p, s)
        if not a["solvable"]:
            errs.append("名题%d 需要猜测" % n)
        if a["lv"] != it["lv"]:
            errs.append("名题%d 记录 lv=%d 实测 %d" % (n, it["lv"], a["lv"]))
        if not it["src"] or not it["lic"]:
            errs.append("名题%d 缺来源/授权" % n)

    if verbose:
        print("题库校验: %d 主线 / %d 残局 / %d 名题" % (len(levels), len(endgames), len(classics)))
        for c in range(6):
            seg = levels[c * 10:(c + 1) * 10]
            print("  第%d章 %-4s L%s 空格%d..%d 步%d..%d 技巧=%s" % (
                c + 1, CH_NAMES[c],
                sorted({x["lv"] for x in seg}),
                min(x["holes"] for x in seg), max(x["holes"] for x in seg),
                min(x["steps"] for x in seg), max(x["steps"] for x in seg),
                "/".join(sorted({t for x in seg for t in x["tech"].split("+")}))))
        if errs:
            print("校验失败 %d 项:" % len(errs))
            for e in errs[:40]:
                print("  - " + e)
        else:
            print("校验通过。")
    return errs


# --------------------------------------------------------------- 注入
def lua_levels(levels):
    out = [M_P[0],
           "-- 60 关: 逐题实测「唯一解 / 不用猜 / 所需最高技巧 / 开局首步可见性」。",
           "-- lv: 1 唯一候选·隐性唯一 / 2 数对 / 3 区块·三数组 / 4 X-Wing",
           "-- holes: 空格数; steps: 人类解法步数; tech: 实际用到的技巧",
           "-- 第 1 章为教学关, 每题都保证「开局存在一处显性唯一」。",
           "local PUZZLE_DATA = {"]
    for n, it in enumerate(levels, 1):
        out.append('  {p="%s", s="%s", lv=%d, holes=%d, steps=%d, tech="%s"}, -- %02d %s'
                   % (it["p"], it["s"], it["lv"], it["holes"], it["steps"],
                      it["tech"], n, CH_NAMES[it["ch"]]))
    out += ["}", M_P[1]]
    return "\n".join(out)


def lua_endgames(items):
    out = [M_E[0],
           "-- 收官残局: 从完整盘面挖 4..8 格, 开局每个空格都能直接看出, 唯一解。",
           "-- tag = 短标题; tip = 一句话说明",
           "local ENDGAME_DATA = {"]
    tags = ["最后一格", "缺口的角", "补完这一行", "右边收口",
            "十字缺口", "终局六格"]
    tips = ["整盘只剩一个空格, 填上就完成了。",
            "四角各缺一个数字, 从缺口最少的宫开始看。",
            "这一行快满了, 先把它补完再动别的。",
            "右侧一列缺两格, 用同行的数字排除。",
            "缺口连成十字, 中间那格是被三个方向同时约束的。",
            "一次补六格, 每格都能单独看出答案。"]
    for n, it in enumerate(items):
        out.append('  {p="%s", s="%s", tag="%s", tip="%s"},'
                   % (it["p"], it["s"], tags[n], tips[n]))
    out += ["}", M_E[1]]
    return "\n".join(out)


def lua_classics(items):
    out = [M_C[0],
           "-- 名题精解: 按技巧各一道, 全部为本机工具生成 + 唯一解 + 不用猜 校验过的原创题。",
           "-- 不冒充历史名题、不使用来源不明的题目; src/lic 明确记录。",
           "local CLASSIC_DATA = {"]
    for it in items:
        out.append('  {p="%s", s="%s", name="%s", lv=%d, tech="%s",'
                   % (it["p"], it["s"], it["name"], it["lv"], it["tech"]))
        out.append('   note="%s", src="%s", lic="%s"},'
                   % (it["note"], it["src"], it["lic"]))
    out += ["}", M_C[1]]
    return "\n".join(out)


def inject(txt, begin, end, block):
    if begin in txt and end in txt:
        return re.sub(re.escape(begin) + r".*?" + re.escape(end), lambda _m: block, txt,
                      count=1, flags=re.S)
    return txt


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--seed", type=int, default=20261108)
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--dry", action="store_true")
    args = ap.parse_args()

    t0 = time.time()
    if args.check:
        return 0 if not verify(*read_all()) else 1

    rng = random.Random(args.seed)
    org = reorganise(rng)
    if not org:
        return 2
    levels, _pool, dropped = org

    endgames = []
    for k, holes in enumerate([4, 5, 6, 7, 5, 6]):
        got = build_endgame(rng, holes)
        if not got:
            print("残局 %d 构造失败" % (k + 1), file=sys.stderr)
            return 2
        endgames.append({"p": got[0], "s": got[1]})
    # 按空格数从少到多排: 收官难度递进
    endgames.sort(key=lambda x: sum(1 for c in x["p"] if c == "0"))

    classics = []
    for name, want, lo, hi, note in CLASSIC_SPEC:
        got = build_classic(rng, want, lo, hi)
        if not got:
            print("名题「%s」构造失败" % name, file=sys.stderr)
            return 2
        classics.append({"p": got[0], "s": got[1], "name": name, "lv": got[2]["lv"],
                         "tech": got[2]["tech"], "note": note,
                         "src": "原创-本机工具生成",
                         "lic": "随 LinTOS 固件分发"})

    errs = verify(levels, endgames, classics)
    print("生成用时 %.1fs" % (time.time() - t0))
    if errs:
        print("校验未通过, 不写入", file=sys.stderr)
        return 2
    if args.dry:
        return 0

    txt = open(APP, encoding="utf-8").read()
    for (b, e), block in ((M_P, lua_levels(levels)),
                          (M_E, lua_endgames(endgames)),
                          (M_C, lua_classics(classics))):
        if b not in txt or e not in txt:
            print("找不到标记块, 未写入: %s" % b, file=sys.stderr)
            return 2
        new = inject(txt, b, e, block)
        txt = new
    open(APP, "w", encoding="utf-8").write(txt)
    print("已写入 %s" % APP)
    if dropped:
        print("未采用(旧题): %s" % ",".join("旧%02d" % x["old"] for x in dropped))
    return 0


def read_all():
    txt = open(APP, encoding="utf-8").read()

    def grab(b, e):
        m = re.search(re.escape(b) + r".*?" + re.escape(e), txt, re.S)
        return m.group(0) if m else ""

    lp = []
    for mm in re.finditer(r'\{p="([0-9]{81})", s="([0-9]{81})", lv=(\d+), holes=(\d+), '
                          r'steps=(\d+), tech="([^"]+)"\}', grab(*M_P)):
        lp.append({"p": mm.group(1), "s": mm.group(2), "lv": int(mm.group(3)),
                   "holes": int(mm.group(4)), "steps": int(mm.group(5)),
                   "tech": mm.group(6), "ch": (len(lp)) // 10})
    le = [{"p": m.group(1), "s": m.group(2)}
          for m in re.finditer(r'\{p="([0-9]{81})", s="([0-9]{81})", tag=', grab(*M_E))]
    lc = []
    for m in re.finditer(r'\{p="([0-9]{81})", s="([0-9]{81})", name="([^"]+)", lv=(\d+), '
                         r'tech="([^"]+)",\s*\n\s*note="([^"]*)", src="([^"]*)", '
                         r'lic="([^"]*)"\}', grab(*M_C)):
        lc.append({"p": m.group(1), "s": m.group(2), "name": m.group(3),
                   "lv": int(m.group(4)), "tech": m.group(5), "note": m.group(6),
                   "src": m.group(7), "lic": m.group(8)})
    return lp, le, lc


if __name__ == "__main__":
    sys.exit(main())
