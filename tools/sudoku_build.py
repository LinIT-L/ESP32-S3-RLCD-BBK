# -------------------------------------------------------------- 残局 / 名题
def build_endgame(rng, holes):
    """收官残局: 挖 holes 格, 开局每个空格都是「显性唯一」, 唯一解。"""
    for _ in range(6000):
        sol = sg.make_solution(rng)
        p = list(sol)
        idx = list(range(81))
        rng.shuffle(idx)
        for i in idx[:holes]:
            p[i] = 0
        if sum(1 for v in p if v == 0) != holes:
            continue
        if sg.count_solutions(p, 2) != 1:
            continue
        a = analyse(p, sol)
        if not a["solvable"] or a["lv"] != 1:
            continue
        if a["first_naked"] != holes:      # 每个空格都能直接看出来 ⇒ 真收官
            continue
        return sg.to_str(p), sg.to_str(sol), a
    return None


def build_classic(rng, want, holes_lo, holes_hi, cap=40000):
    """按技巧定向生成一道名题: want(lv, used, holes, steps) -> bool。"""
    for _ in range(cap):
        sol = sg.make_solution(rng)
        p, _h = sg.dig(sol, rng.randint(holes_lo, holes_hi), rng)
        holes = sum(1 for v in p if v == 0)
        if not (holes_lo <= holes <= holes_hi):
            continue
        if sg.count_solutions(p, 2) != 1:
            continue
        a = analyse(p, sol)
        if not a["solvable"]:
            continue
        if not want(a["lv"], a["used"], holes, a["steps"]):
            continue
        return sg.to_str(p), sg.to_str(sol), a
    return None


