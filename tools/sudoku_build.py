# ----------------------------------------------------------------- 局面分析
def parse(s):
    return [int(ch) for ch in s]


def first_moves(p):
    """开局第一步的三种可见性: 显性唯一 / 单元只剩一格 / 隐性唯一。"""
    c = sg.initial_candidates(p)
    naked = [i for i in range(81) if p[i] == 0 and sg.bit_count(c[i]) == 1]
    fh = []
    for k, u in enumerate(sg.UNITS):
        empt = [i for i in u if p[i] == 0]
        if len(empt) == 1:
            fh.append((k, empt[0]))
    hidden = []
    for k, u in enumerate(sg.UNITS):
        for d in range(1, 10):
            if any(p[i] == d for i in u):
                continue
            spots = [i for i in u if p[i] == 0 and (c[i] & (1 << (d - 1)))]
            if len(spots) == 1:
                hidden.append((k, d, spots[0]))
    return naked, fh, hidden


def unit_kind(k):
    return "行" if k < 9 else ("列" if k < 18 else "宫")


def analyse(p, s):
    holes = sum(1 for v in p if v == 0)
    ok, lv, used, steps = sg.human_solve(p)
    naked, fh, hidden = first_moves(p)
    return {
        "holes": holes, "solvable": ok, "lv": lv, "used": used, "steps": steps,
        "first_naked": len(naked), "first_naked_cells": naked,
        "first_fh": fh, "first_hidden": len(hidden),
        "tech": "+".join(sorted(used)),
    }


# --------------------------------------------------------------- 第 1 章构造
def build_teaching(rng, spec):
    """定向构造教学题。

    spec: (holes_target, kind)  kind ∈ {"one","row","col","box","mix"}
      one  : 只挖 1 格 —— 同时是本行/本列/本宫的最后空格，一上手就懂三条规则
      row  : 某行只剩 1 空格，但该格所在宫还有别的空格 ⇒ 必须看行
      col  : 同上，列
      box  : 某宫只剩 1 空格，但同一行还有别的空格 ⇒ 必须看宫
      mix  : 随机挖空，只要求唯一解 + 纯显性唯一可解
    """
    target, kind = spec
    for _ in range(4000):
        sol = sg.make_solution(rng)
        p = list(sol)
        if kind == "one":
            p[rng.randrange(81)] = 0
        elif kind in ("row", "col", "box"):
            if kind == "row":
                r = rng.randrange(9)
                c = rng.randrange(9)
                p[r * 9 + c] = 0                       # 本行唯一空格
                br, bc = (r // 3) * 3, (c // 3) * 3
                others = [(rr, cc) for rr in range(br, br + 3)
                          for cc in range(bc, bc + 3)
                          if (rr, cc) != (r, c)]
                r2, c2 = rng.choice(others)
                p[r2 * 9 + c2] = 0                     # 同宫再挖一格 ⇒ 不能靠宫
                r3 = rng.randrange(9)
                c3 = rng.randrange(9)
                p[r3 * 9 + c3] = 0
            elif kind == "col":
                r = rng.randrange(9)
                c = rng.randrange(9)
                p[r * 9 + c] = 0
                br, bc = (r // 3) * 3, (c // 3) * 3
                others = [(rr, cc) for rr in range(br, br + 3)
                          for cc in range(bc, bc + 3)
                          if (rr, cc) != (r, c)]
                r2, c2 = rng.choice(others)
                p[r2 * 9 + c2] = 0
                r3 = rng.randrange(9)
                c3 = rng.randrange(9)
                p[r3 * 9 + c3] = 0
            else:                                      # box
                r = rng.randrange(9)
                c = rng.randrange(9)
                p[r * 9 + c] = 0                       # 本宫唯一空格
                c2 = rng.choice([x for x in range(9) if x // 3 != c // 3])
                p[r * 9 + c2] = 0                      # 同行另挖 ⇒ 不能只看行
                r3 = rng.randrange(9)
                c3 = rng.randrange(9)
                p[r3 * 9 + c3] = 0
        else:
            p, _ = sg.dig(sol, target, rng)
        holes = sum(1 for v in p if v == 0)
        if kind == "mix" and holes < target - 2:
            continue
        if holes > target and kind != "one":
            continue
        if sg.count_solutions(p, 2) != 1:
            continue
        a = analyse(p, sol)
        # 教学硬门槛: 不许用比「唯一候选」更强的技巧, 首步必须是显性唯一
        if not a["solvable"] or a["lv"] != 1 or a["first_naked"] == 0:
            continue
        if kind == "row":
            if not any(unit_kind(k) == "行" and cell in a["first_naked_cells"] for k, cell in a["first_fh"]):
                continue
        if kind == "col":
            if not any(unit_kind(k) == "列" and cell in a["first_naked_cells"] for k, cell in a["first_fh"]):
                continue
        if kind == "box":
            if not any(unit_kind(k) == "宫" and cell in a["first_naked_cells"] for k, cell in a["first_fh"]):
                continue
            # 该宫唯一空格, 但同行还有别的空格 ⇒ 真的必须看宫
            k, cell = [x for x in a["first_fh"] if unit_kind(x[0]) == "宫"][0]
            rowcells = sg.UNITS[cell // 9]
            if sum(1 for i in rowcells if p[i] == 0) < 2:
                continue
        return sg.to_str(p), sg.to_str(sol), a
    return None


