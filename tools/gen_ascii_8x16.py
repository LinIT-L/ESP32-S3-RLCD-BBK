    for i, bs in enumerate(DATA):
        code = 0x20 + i
        ch = chr(code)
        esc = ch
        if esc in ("\\", '"', "'"):
            esc = "\\%s" % esc
        out_lines.append("  { %s },  /* '%s' (0x%02X) */" % (
            ", ".join("0x%02X" % b for b in bs), esc, code))
    out_lines.append("};")
    out_lines.append("#endif")

    out_path = os.path.normpath(os.path.join(
        os.path.dirname(__file__), "..", "components", "menu", "font8x16_zh.h"))
    with open(out_path, "w") as f:
        f.write("\n".join(out_lines) + "\n")
    print(f"已生成 {out_path} ({len(DATA)} 字符)")

