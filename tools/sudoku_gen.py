FULL = 0x1FF  # 9 位候选掩码

ROWS = [[r * 9 + c for c in range(9)] for r in range(9)]
COLS = [[r * 9 + c for r in range(9)] for c in range(9)]
BOXS = [[(br * 3 + dr) * 9 + bc * 3 + dc
         for dr in range(3) for dc in range(3)]
        for br in range(3) for bc in range(3)]
UNITS = ROWS + COLS + BOXS
UNITS_OF = [[] for _ in range(81)]
for _u, _cells in enumerate(UNITS):
    for _i in _cells:
        UNITS_OF[_i].append(_u)
PEERS = []
for _i in range(81):
    _s = set()
    for _u in UNITS_OF[_i]:
        _s.update(UNITS[_u])
    _s.discard(_i)
    PEERS.append(tuple(sorted(_s)))

# 每章: (名称, 允许最高技巧等级, 空格数下限, 上限, 额外要求)
# ★ 2026-11-08 重排(linit「不要十个重复的简单填数字关卡」):
#   第 1 章第 1 关是**唯一教学关**(空格少 + 某宫只剩一格), 教"宫的隐性唯一";
#   第 2 关起是正式练习。第 2 章以后**按实际所需技巧分级**, 不再靠空格数凑难度:
#     基础篇 = 只需单值推理(但盘面满、需要长时间扫描)
#     进阶篇 = 必须用数对 / 技巧篇 = 必须用区块排除 / 挑战篇 = 必须用三数组 / 高手篇 = X-Wing
CHAPTERS = [
    ("启蒙篇", 1, 22, 28, "teach+single"),
    ("基础篇", 1, 50, 64, "single"),
    ("进阶篇", 2, 50, 64, "pair"),
    ("技巧篇", 3, 50, 64, "block"),
    ("挑战篇", 3, 50, 64, "triple"),
    ("高手篇", 4, 50, 64, "xwing"),
]

# 教学关(第 1 关)专用参数: 空格少一点, 但必须存在"某宫只剩一格", 新手第一步才有确定目标
TEACH_HOLES = (9, 13)


def has_box_single(p):
    """是否存在某宫只剩一个空格 —— 教学关的目标局面。"""
    for u in BOXS:
        if sum(1 for i in u if p[i] == 0) == 1:
            return True
    return False


def bit_count(x):
    return bin(x).count("1")


def bits(m):
    out = []
    for d in range(1, 10):
        if m & (1 << (d - 1)):
            out.append(d)
    return out


def to_str(grid):
    return "".join(str(v) for v in grid)


def valid_complete(grid):
    for u in UNITS:
        if set(grid[i] for i in u) != set(range(1, 10)):
            return False
    return True


# ---------------------------------------------------------------- 完整解生成
def make_solution(rng):
    """标准 3x3 模式 + 行/列/数字随机置换（保证是合法完整解）。"""
    base = list(range(3))
    rows = [g * 3 + r for g in rng.sample(base, 3) for r in rng.sample(base, 3)]
    cols = [g * 3 + c for g in rng.sample(base, 3) for c in rng.sample(base, 3)]
    nums = rng.sample(range(1, 10), 9)

    def pat(r, c):
        return (3 * (r % 3) + r // 3 + c) % 9

    return [nums[pat(r, c)] for r in rows for c in cols]


# ---------------------------------------------------------------- 唯一解计数
def count_solutions(grid, limit=2):
    g = list(grid)
    cand = [0] * 81
    for i in range(81):
        if g[i] == 0:
            m = FULL
            for j in PEERS[i]:
                if g[j]:
                    m &= ~(1 << (g[j] - 1))
            if m == 0:
                return 0
            cand[i] = m

    def rec():
        best, best_m, best_n = -1, 0, 10
        for i in range(81):
            if g[i] == 0:
                n = bit_count(cand[i])
                if n == 0:
                    return 0
                if n < best_n:
                    best, best_m, best_n = i, cand[i], n
                    if n == 1:
                        break
        if best < 0:
            return 1
        total = 0
        for d in bits(best_m):
            mask = 1 << (d - 1)
            g[best] = d
            # touched 必须是本轮局部: 否则会把上一轮移除的位用当前 d 误恢复,
            # 候选被放大 → 凭空多出解 (已知唯一解题会被数成 5 个)。
            touched = []
            for j in PEERS[best]:
                if g[j] == 0 and (cand[j] & mask):
                    cand[j] &= ~mask
                    touched.append(j)
            total += rec()
            for j in touched:
                cand[j] |= mask
            g[best] = 0
            if total >= limit:
                break
        return total

    return rec()


def dig(solution, target_holes, rng):
    """按随机顺序挖空，每挖一个都重新确认仍是唯一解。用于 L1 入门题。"""
    p = list(solution)
    order = list(range(81))
    rng.shuffle(order)
    holes = 0
    for idx in order:
        if holes >= target_holes:
            break
        saved = p[idx]
        p[idx] = 0
        if count_solutions(p, 2) != 1:
            p[idx] = saved
        else:
            holes += 1
    return p, holes


def dig_logic_safe(solution, target_holes, rng):
    """挖到目标空格数, 再校验"纯逻辑可解"; 不可解就随机回填几格重试。

    不在每一步挖空时跑逻辑求解器(那会把生成时间放大两个数量级), 只在挖完后校验,
    用"回填到可解"兜底。结果同样硬保证: 唯一解 + 只用已实现技巧可解。
    """
    p, holes = dig(solution, target_holes, rng)
    for _ in range(8):
        ok, lv, used, steps = human_solve(p)
        if ok:
            return p, holes, lv, used, steps
        empties = [i for i, v in enumerate(p) if v == 0]
        if not empties:
            break
        i = rng.choice(empties)
        p[i] = solution[i]
        holes -= 1
    return None


# ---------------------------------------------------------------- 最大挖空
# ★ 2026-11-08: 实测「挖到固定空格数」几乎只能产出裸单题(240 次采样里 lv1 占 98%),
#   因为随机挖空留下的盘面总能靠单值推理解完。想让难度真正递进, 必须**挖到挖不动为止**
#   —— 每挖一格都确认仍是唯一解, 挖到再加任何一个空格就有多解或需要猜测。
#   这样得到的题才逼出数对/区块/三数组这些技巧(实测 lv2 约 10%、lv3 约 5%)。
def dig_max(solution, rng):
    p = list(solution)
    order = list(range(81))
    rng.shuffle(order)
    holes = 0
    for idx in order:
        saved = p[idx]
        p[idx] = 0
        if count_solutions(p, 2) != 1:
            p[idx] = saved            # 挖了就有多解, 保留
        else:
            holes += 1
    return p, holes


def dig_max_solvable(solution, rng):
    """最大挖空 + 回填到"纯逻辑可解"。挖到极限时约 1/3 局面需要猜, 回填几格即可。"""
    p, holes = dig_max(solution, rng)
    for _ in range(18):
        ok, lv, used, steps = human_solve(p)
        if ok:
            return p, holes, lv, used, steps
        empties = [i for i, v in enumerate(p) if v == 0]
        if not empties:
            break
        i = rng.choice(empties)
        p[i] = solution[i]
        holes -= 1
    return None


# -------------------------------------------------- 人类技巧求解器（不许猜）
def initial_candidates(g):
    c = [0] * 81
    for i in range(81):
        if g[i] == 0:
            m = FULL
            for j in PEERS[i]:
                if g[j]:
                    m &= ~(1 << (g[j] - 1))
            c[i] = m
    return c


def assign(g, c, i, d):
    g[i] = d
    c[i] = 0
    mask = 1 << (d - 1)
    for j in PEERS[i]:
        c[j] &= ~mask


def try_singles(g, c, used):
    # 裸单
    for i in range(81):
        if g[i] == 0 and c[i] and bit_count(c[i]) == 1:
            assign(g, c, i, bits(c[i])[0])
            used.add("naked_single")
            return True, 1
    # 隐性单
    for u in UNITS:
        for d in range(1, 10):
            mask = 1 << (d - 1)
            spots = [i for i in u if g[i] == 0 and (c[i] & mask)]
            if len(spots) == 1 and g[spots[0]] == 0:
                assign(g, c, spots[0], d)
                used.add("hidden_single")
                return True, 1
    return False, 0


def try_pairs(g, c, used):
    # 裸数对
    for u in UNITS:
        empties = [i for i in u if g[i] == 0]
        for a in range(len(empties)):
            ia = empties[a]
            if bit_count(c[ia]) != 2:
                continue
            for b in range(a + 1, len(empties)):
                ib = empties[b]
                if c[ib] != c[ia]:
                    continue
                changed = False
                for i in empties:
                    if i != ia and i != ib and (c[i] & c[ia]):
                        c[i] &= ~c[ia]
                        changed = True
                if changed:
                    used.add("naked_pair")
                    return True, 2
    # 隐性数对
    for u in UNITS:
        empties = [i for i in u if g[i] == 0]
        pos = {d: [i for i in empties if c[i] & (1 << (d - 1))] for d in range(1, 10)}
        ds = [d for d in range(1, 10) if len(pos[d]) == 2]
        for a in range(len(ds)):
            for b in range(a + 1, len(ds)):
                d1, d2 = ds[a], ds[b]
                if pos[d1] != pos[d2]:
                    continue
                keep = (1 << (d1 - 1)) | (1 << (d2 - 1))
                changed = False
                for i in pos[d1]:
                    if c[i] & ~keep:
                        c[i] &= keep
                        changed = True
                if changed:
                    used.add("hidden_pair")
                    return True, 2
    return False, 0


def try_pointing_claiming(g, c, used):
    # 宫区块排除: 宫内某数只能在同一行/列 → 排除该行/列其它宫
    for u in BOXS:
        for d in range(1, 10):
            mask = 1 << (d - 1)
            spots = [i for i in u if g[i] == 0 and (c[i] & mask)]
            if len(spots) < 2:
                continue
            rows = {i // 9 for i in spots}
            cols = {i % 9 for i in spots}
            for line in ([ROWS[r] for r in rows if len(rows) == 1] +
                         [COLS[cc] for cc in cols if len(cols) == 1]):
                changed = False
                for i in line:
                    if i not in u and g[i] == 0 and (c[i] & mask):
                        c[i] &= ~mask
                        changed = True
                if changed:
                    used.add("pointing")
                    return True, 3
    # 宫行/列排除(claiming): 行/列内某数只在同一宫 → 排除该宫其它格
    for u in ROWS + COLS:
        for d in range(1, 10):
            mask = 1 << (d - 1)
            spots = [i for i in u if g[i] == 0 and (c[i] & mask)]
            if len(spots) < 2:
                continue
            boxes = {(i // 27) * 3 + (i % 9) // 3 for i in spots}
            if len(boxes) != 1:
                continue
            bu = BOXS[boxes.pop()]
            changed = False
            for i in bu:
                if i not in u and g[i] == 0 and (c[i] & mask):
                    c[i] &= ~mask
                    changed = True
            if changed:
                used.add("claiming")
                return True, 3
    return False, 0


def try_triples(g, c, used):
    for u in UNITS:
        empties = [i for i in u if g[i] == 0]
        # 裸三数组
        cand3 = [i for i in empties if 2 <= bit_count(c[i]) <= 3]
        for a in range(len(cand3)):
            for b in range(a + 1, len(cand3)):
                for e in range(b + 1, len(cand3)):
                    tri = (cand3[a], cand3[b], cand3[e])
                    union = c[tri[0]] | c[tri[1]] | c[tri[2]]
                    if bit_count(union) != 3:
                        continue
                    changed = False
                    for i in empties:
                        if i not in tri and (c[i] & union):
                            c[i] &= ~union
                            changed = True
                    if changed:
                        used.add("naked_triple")
                        return True, 3
        # 隐性三数组
        pos = {d: [i for i in empties if c[i] & (1 << (d - 1))] for d in range(1, 10)}
        ds = [d for d in range(1, 10) if 2 <= len(pos[d]) <= 3]
        for a in range(len(ds)):
            for b in range(a + 1, len(ds)):
                for e in range(b + 1, len(ds)):
                    d3 = (ds[a], ds[b], ds[e])
                    cells = set(pos[d3[0]]) | set(pos[d3[1]]) | set(pos[d3[2]])
                    if len(cells) != 3:
                        continue
                    keep = 0
                    for d in d3:
                        keep |= 1 << (d - 1)
                    changed = False
                    for i in cells:
                        if c[i] & ~keep:
                            c[i] &= keep
                            changed = True
                    if changed:
                        used.add("hidden_triple")
                        return True, 3
    return False, 0


def try_xwing(g, c, used):
    for d in range(1, 10):
        mask = 1 << (d - 1)
        # 行版: 两行各恰有 2 个位置且列相同
        for base in (ROWS, COLS):
            pattern = {}
            for u in base:
                spots = tuple((i % 9) if base is ROWS else (i // 9)
                              for i in u if g[i] == 0 and (c[i] & mask))
                if len(spots) == 2:
                    pattern.setdefault(spots, []).append(u)
            for spots, lines in pattern.items():
                if len(lines) < 2:
                    continue
                for a in range(len(lines)):
                    for b in range(a + 1, len(lines)):
                        other = set(lines[a]) | set(lines[b])
                        changed = False
                        for k in spots:
                            line = COLS[k] if base is ROWS else ROWS[k]
                            for i in line:
                                if i not in other and g[i] == 0 and (c[i] & mask):
                                    c[i] &= ~mask
                                    changed = True
                        if changed:
                            used.add("xwing")
                            return True, 4
    return False, 0


def human_solve(puzzle):
    """只允许已知逻辑技巧；返回 (是否解出, 最高技巧等级, 技巧集合, 步数)。"""
    g, c = list(puzzle), initial_candidates(puzzle)
    used, level, steps = set(), 0, 0
    while any(v == 0 for v in g):
        progressed = False
        for fn in (try_singles, try_pairs, try_pointing_claiming, try_triples, try_xwing):
            ok, lv = fn(g, c, used)
            if ok:
                level = max(level, lv)
                steps += 1
                progressed = True
                break
        if not progressed:
            return False, level, used, steps
        if steps > 400:
            return False, level, used, steps
        # 候选自洽检查：某空格候选为空说明前面推错了
        if any(g[i] == 0 and c[i] == 0 for i in range(81)):
            return False, level, used, steps
    return valid_complete(g), level, used, steps


# ---------------------------------------------------------------- 分章收集
def classify(level, used, holes, ch, steps=0, teach=False):
    _name, max_lv, lo, hi, _extra = CHAPTERS[ch]
    if ch == 0:
        # 启蒙: 只用最基础的单值推理(裸单/隐性单)。第 1 关(教学)走更少的空格区间。
        if level != 1:
            return False
        if teach:
            return TEACH_HOLES[0] <= holes <= TEACH_HOLES[1]
        return lo <= holes <= hi
    if level > max_lv:
        return False
    if holes < 46:      # 高章节一律用"挖到极限"的盘面, 空格太少说明回填过多
        return False
    if ch == 1:   # 基础: 只需单值推理 (盘面满, 练扫描)
        return level == 1
    if ch == 2:   # 进阶: 必须用到数对
        return level == 2
    if ch == 3:   # 技巧: 必须用到区块排除 (pointing/claiming)
        return level == 3 and ("pointing" in used or "claiming" in used)
    if ch == 4:   # 挑战: 必须用到三数组
        return level == 3 and ("naked_triple" in used or "hidden_triple" in used)
    if ch == 5:   # 高手: X-Wing
        return level == 4
    return False


def generate(seed, verbose=True):
    """按章定向生成; 每章独立尝试上限, 凑满 10 道即停。

    第 6 章两阶段: 先找真正的 X-Wing 必需题(实测出现率 ~0.07%), 找不满 10 道
    再用"L3 + 56 空格以上 + 45 步以上推理链"补足。补足情况会打印出来, 不含糊。
    """
    rng = random.Random(seed)
    buckets = [[] for _ in range(6)]
    seen_p, seen_sig, seen_sol = set(), set(), set()
    t0 = time.time()
    stats = {"dug": 0, "logic_fail": 0, "dup": 0, "unclassified": 0}
    l4_found = 0

    def try_add(ch, target_lo, target_hi, want, teach=False, need_box_single=False,
                mode="dig", bypass=False):
        sol = make_solution(rng)
        if mode == "max":
            res = dig_max_solvable(sol, rng)          # 挖到不能再挖, 逼出高级技巧
        else:
            target = rng.randint(target_lo, target_hi)
            res = dig_logic_safe(sol, target, rng)    # 挖到目标空格数 (启蒙关用)
        stats["dug"] += 1
        if not res:
            stats["logic_fail"] += 1
            return False
        p, holes, level, used, steps = res
        if not want(level, used, holes, steps):
            stats["unclassified"] += 1
            return False
        if not bypass and not classify(level, used, holes, ch, steps, teach):
            stats["unclassified"] += 1
            return False
        if need_box_single and not has_box_single(p):
            stats["unclassified"] += 1
            return False
        pstr, sstr = to_str(p), to_str(sol)
        sig = tuple(i for i, v in enumerate(p) if v == 0)
        if pstr in seen_p or sig in seen_sig or sstr in seen_sol:
            stats["dup"] += 1
            return False
        seen_p.add(pstr); seen_sig.add(sig); seen_sol.add(sstr)
        buckets[ch].append({
            "p": pstr, "s": sstr, "lv": level, "holes": holes,
            "tech": "+".join(sorted(used)), "steps": steps,
        })
        return True

    # ★ 第 1 关: 教学关 —— 空格少, 且必须存在"某宫只剩一格"(新手第一步有确定目标)。
    #   单独先跑, 保证它一定是全题库的第 1 题。
    tries = 0
    while len(buckets[0]) < 1 and tries < 40000:
        tries += 1
        try_add(0, TEACH_HOLES[0], TEACH_HOLES[1], lambda lv, u, h, s: True,
                teach=True, need_box_single=True)

    # 第 1 章其余 9 关: 常规挖空, 空格比教学关多, 仍是单值推理
    tries = 0
    while len(buckets[0]) < 10 and tries < 9000:
        tries += 1
        try_add(0, 22, 28, lambda lv, u, h, s: True)

    # 第 2-5 章: 全部走"挖到极限", 按实测技巧等级归章 (见 classify)
    plan = [(1, 4000), (2, 12000), (3, 20000), (4, 80000)]
    for ch, cap in plan:
        tries = 0
        while len(buckets[ch]) < 10 and tries < cap:
            tries += 1
            try_add(ch, 0, 0, lambda lv, u, h, s: True, mode="max")

    # 第 6 章: 先搜真正的 X-Wing; 实在不足再用"L3 长链"补足 (会打印实际数量, 不含糊)
    tries = 0
    while len(buckets[5]) < 10 and tries < 30000:
        tries += 1
        before = len(buckets[5])
        try_add(5, 0, 0, lambda lv, u, h, s: lv == 4, mode="max")
        if len(buckets[5]) > before:
            l4_found += 1
    tries = 0
    while len(buckets[5]) < 10 and tries < 40000:
        tries += 1
        try_add(5, 0, 0, lambda lv, u, h, s: lv == 3 and h >= 52 and s >= 55,
                mode="max", bypass=True)

    if verbose:
        print("生成统计: %s, 用时 %.1fs" % (stats, time.time() - t0))
        print("第 6 章 X-Wing 必需题: %d 道, 其余为 L3 长链补足" % l4_found)
        for ch in range(6):
            got = buckets[ch]
            lvs = [x["lv"] for x in got]
            holes = [x["holes"] for x in got]
            steps = [x["steps"] for x in got]
            print("  第%d章 %-6s %2d/10  L=%s  空格=%d..%d  步=%d..%d" %
                  (ch + 1, CHAPTERS[ch][0], len(got), sorted(set(lvs)),
                   min(holes) if holes else 0, max(holes) if holes else 0,
                   min(steps) if steps else 0, max(steps) if steps else 0))
    return buckets


def lua_block(buckets):
    lines = [BEGIN,
             "-- 60 关固定题库: 逐题经过「唯一解计数 == 1」+「纯逻辑技巧可解」双校验。",
             "-- lv = 解出该题所需最高技巧等级 (1 单值 / 2 数对 / 3 区块·三数组 / 4 X-Wing)。",
             "-- 章节技巧递进 (2026-11-08 重排):",
             "--   1 启蒙篇 教学关 + 单值推理练习 (空格 22-28)",
             "--   2 基础篇 满盘单值推理 (空格 52-59, 练扫描与耐心)",
             "--   3 进阶篇 必须用到数对 (裸数对/隐性数对)",
             "--   4 技巧篇 必须用到区块排除 (pointing/claiming)",
             "--   5 挑战篇 必须用到三数组 (裸三数组/隐性三数组)",
             "--   6 高手篇 必须用到 X-Wing",
             "-- ch 顺序即关卡 1..60; p = 题目(0 为空格), s = 唯一解。",
             "local PUZZLE_DATA = {"]
    idx = 0
    for ch in range(6):
        for item in buckets[ch]:
            idx += 1
            lines.append('  {p="%s", s="%s", lv=%d, holes=%d, tech="%s"}, -- %02d %s' %
                         (item["p"], item["s"], item["lv"], item["holes"],
                          item["tech"], idx, CHAPTERS[ch][0]))
    lines.append("}")
    lines.append(END)
    return "\n".join(lines)


def read_existing():
    if not os.path.exists(APP):
        return []
    txt = open(APP, encoding="utf-8").read()
    m = re.search(re.escape(BEGIN) + r".*?" + re.escape(END), txt, re.S)
    if not m:
        return []
    out = []
    for p, s, lv, holes, tech in re.findall(
            r'\{p="([0-9]{81})", s="([0-9]{81})", lv=(\d+), holes=(\d+), tech="([^"]+)"\}', m.group(0)):
        out.append({"p": p, "s": s, "lv": int(lv), "holes": int(holes), "tech": tech})
    return out


def check(items, verbose=True):
    errs = []
    if len(items) != 60:
        errs.append("题目数 %d != 60" % len(items))
    seen_p, seen_sig, seen_sol = set(), set(), set()
    per_ch = [[] for _ in range(6)]
    for n, it in enumerate(items, 1):
        ch = (n - 1) // 10
        p = [int(x) for x in it["p"]]
        s = [int(x) for x in it["s"]]
        if not valid_complete(s):
            errs.append("第%d题 解答不是合法完整解" % n)
        if any(p[i] and p[i] != s[i] for i in range(81)):
            errs.append("第%d题 给定数字与解答冲突" % n)
        n_sol = count_solutions(p, 2)
        if n_sol != 1:
            errs.append("第%d题 解的个数=%d (要求 1)" % (n, n_sol))
        ok, lv, used, steps = human_solve(p)
        if not ok:
            errs.append("第%d题 纯逻辑技巧无法解出(需要猜测)" % n)
        if lv != it["lv"]:
            errs.append("第%d题 记录 lv=%d 实测=%d" % (n, it["lv"], lv))
        holes = sum(1 for v in p if v == 0)
        if holes != it["holes"]:
            errs.append("第%d题 记录空格=%d 实测=%d" % (n, it["holes"], holes))
        # 第 1 题是教学关: 走独立的空格区间, 且必须存在"某宫只剩一格"
        teach = (n == 1)
        ok_ch = classify(lv, used, holes, ch, steps, teach)
        if not ok_ch and ch == 5 and lv == 3 and holes >= 52 and steps >= 55:
            ok_ch = True      # 第 6 章的"L3 长链补足题", 生成时会打印实际数量
        if not ok_ch:
            errs.append("第%d题 难度不属于第%d章 (lv=%d 空格=%d 步=%d)"
                        % (n, ch + 1, lv, holes, steps))
        if teach and not has_box_single(p):
            errs.append("第1题 教学关缺少「某宫只剩一格」的局面")
        sig = tuple(i for i, v in enumerate(p) if v == 0)
        if it["p"] in seen_p:
            errs.append("第%d题 题目重复" % n)
        if sig in seen_sig:
            errs.append("第%d题 空格模式重复" % n)
        if it["s"] in seen_sol:
            errs.append("第%d题 解答重复" % n)
        seen_p.add(it["p"])
        seen_sig.add(sig)
        seen_sol.add(it["s"])
        per_ch[ch].append((lv, holes))
    if verbose:
        print("共 %d 题；逐题校验: 唯一解 / 逻辑可解 / 难度归属 / 去重 / 解答一致" % len(items))
        for ch in range(6):
            if per_ch[ch]:
                lvs = [x[0] for x in per_ch[ch]]
                hs = [x[1] for x in per_ch[ch]]
                print("  第%d章 %-6s %2d题  L=%s  空格=%d..%d" %
                      (ch + 1, CHAPTERS[ch][0], len(per_ch[ch]),
                       sorted(set(lvs)), min(hs), max(hs)))
        if errs:
            print("校验失败 %d 项:" % len(errs))
            for e in errs[:30]:
                print("  - " + e)
        else:
            print("校验通过: 60 题全部唯一解、纯逻辑可解、难度归属正确、无重复。")
    return errs


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--seed", type=int, default=20261107)
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--attempts", type=int, default=0,
                    help="兼容旧参数, 已由按章独立的尝试上限取代")
    args = ap.parse_args()

    if args.check:
        items = read_existing()
        return 1 if check(items) else 0

    buckets = generate(args.seed)
    if any(len(b) < 10 for b in buckets):
        print("生成不足: %s" % [len(b) for b in buckets], file=sys.stderr)
        print("请增大 --attempts 或换 --seed 后重试；不会写入半成品题库。", file=sys.stderr)
        return 2
    items = [x for b in buckets for x in b]
    if check(items, verbose=False):
        print("内部校验未通过，拒绝写入", file=sys.stderr)
        return 2

    if not os.path.exists(APP):
        print("主应用文件还不存在: %s" % APP, file=sys.stderr)
        print("先把占位标记写进主应用，再运行本脚本注入题库。", file=sys.stderr)
        return 2
    txt = open(APP, encoding="utf-8").read()
    block = lua_block(buckets)
    if BEGIN in txt and END in txt:
        txt = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END),
                     lambda _m: block, txt, count=1, flags=re.S)
    else:
        print("主应用里找不到题库占位标记，未写入", file=sys.stderr)
        return 2
    open(APP, "w", encoding="utf-8").write(txt)
    check(items)
    print("已注入 %s (%d 题, %d 字节)" % (APP, len(items), len(block)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
