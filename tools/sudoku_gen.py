# -*- coding: utf-8 -*-
"""sudoku_gen.py — 《数独大师》固定题库生成 / 唯一解与难度验证。

为什么是固定题库（而不是在 ESP32 上现场生成）
------------------------------------------------
设备侧现场挖空 + 数解计数既慢又难以稳定保证唯一解。本脚本在主机上一次性生成
60 道题，逐题做两道硬校验，再把结果作为常量表内嵌进单文件 LAPP：

  ① 唯一解：MRV 回溯数解器 count_solutions(puzzle, limit=2) 必须 == 1
  ② 可逻辑解：human_solve() 只允许使用「裸单 / 隐性单 / 裸数对 / 隐性数对 /
     宫区块排除(含宫行排除) / 裸三数组 / 隐性三数组 / X-Wing」，不允许猜。
     解不出来（需要回溯/更高级链）的题直接丢弃。

难度不是按空格数拍脑袋，而是取「解出这道题实际用到的最高技巧等级」：

  L1 裸单 / 隐性单        → 第 1、2 章
  L2 裸数对 / 隐性数对     → 第 3 章
  L3 区块排除 / 三数组     → 第 4、5 章
  L4 X-Wing               → 第 6 章

同时约束空格数随章节递增。生成后 --check 会把题库从 Lua 里读回来重跑全部校验，
因此「题库经过验证」这件事是可复现的，不是一次性口头结论。

用法:
    python3 tools/sudoku_gen.py            # 生成并注入 apps/lua/apps/app/数独大师.lua
    python3 tools/sudoku_gen.py --check    # 只校验现有题库，不改文件
    python3 tools/sudoku_gen.py --seed 7   # 固定随机种子复现
"""
